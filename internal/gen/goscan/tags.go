package goscan

import (
	"errors"
	"fmt"
	"strings"

	"github.com/AlexAli29/orm/internal/gen/model"
)

// The tag grammar is a comma-separated list of directives:
//
//	column:<name>   override the derived column name
//	fk:<name>       use this PostgreSQL constraint for the relation
//	side:local      the declaring entity's table carries the foreign key
//	side:remote     the target entity's table carries it
//	type:<key>      use the configured type mapping under <key>
//	-               exclude the field from reconciliation entirely
//
// Managed mode adds the ones that describe desired schema. They say what the
// column should be, which is a different question from what it is, and
// reconciliation ignores them entirely:
//
//	pk                  the column is part of the primary key
//	identity            GENERATED BY DEFAULT AS IDENTITY
//	identity:always     GENERATED ALWAYS AS IDENTITY
//	unique              a single-column unique constraint
//	default:<expr>      a DEFAULT expression, as SQL
//	generated:<expr>    a stored generated column, as SQL
//	pgtype:<type>       the PostgreSQL type, when the default for the Go type
//	                    is not the one wanted: citext, varchar(255),
//	                    public.user_state
//
// A default is SQL and never a Go value: writing default:true asks PostgreSQL
// for the literal true, and a Go field set to false still stores false. The
// zero value is a value here as everywhere else.
//
// There is no forgiving mode. An unknown key, a missing value or a directive on
// the wrong kind of field is reported, because a tag that is silently ignored is
// a mapping the author believes exists and the tool does not.
const (
	tagIgnore    = "-"
	tagColumn    = "column"
	tagFK        = "fk"
	tagSide      = "side"
	tagType      = "type"
	tagPK        = "pk"
	tagIdentity  = "identity"
	tagUnique    = "unique"
	tagDefault   = "default"
	tagGenerated = "generated"
	tagPGType    = "pgtype"
)

// valuelessTags are the directives written as a bare word.
var valuelessTags = map[string]bool{tagPK: true, tagIdentity: true, tagUnique: true}

// ParseTags parses the `orm` key of a struct tag. It returns the directives it
// understood together with the first error, so that a field with one bad
// directive still contributes the rest.
func ParseTags(structTag string) (model.FieldTags, error) {
	raw, ok := lookupTag(structTag, TagKey)
	if !ok {
		return model.FieldTags{}, nil
	}
	tags := model.FieldTags{Raw: raw}
	if strings.TrimSpace(raw) == "" {
		return tags, errors.New("empty tag; remove it or write orm:\"-\" to exclude the field")
	}

	var firstErr error
	fail := func(err error) {
		if firstErr == nil {
			firstErr = err
		}
	}
	seen := make(map[string]bool)

	// A default or a generated expression is SQL, and SQL contains commas:
	// default:coalesce(a, b) is one directive. The split therefore respects
	// parentheses and quotes rather than cutting at every comma.
	for _, part := range splitDirectives(raw) {
		part = strings.TrimSpace(part)
		if part == "" {
			fail(errors.New("empty directive; remove the stray comma"))
			continue
		}
		if part == tagIgnore {
			if seen[tagIgnore] {
				fail(errors.New(`duplicate "-" directive`))
			}
			seen[tagIgnore] = true
			tags.Ignore = true
			continue
		}
		key, value, found := strings.Cut(part, ":")
		if !found {
			if !valuelessTags[part] {
				fail(fmt.Errorf("directive %q has no value; write %s:<value>", part, part))
				continue
			}
			key = part
		}
		if seen[key] {
			fail(fmt.Errorf("duplicate %s directive", key))
			continue
		}
		seen[key] = true
		if value == "" && !valuelessTags[key] {
			fail(fmt.Errorf("%s: needs a value", key))
			continue
		}
		switch key {
		case tagColumn:
			tags.Column = value
		case tagFK:
			tags.FK = value
		case tagSide:
			side, err := model.ParseFKSide(value)
			if err != nil {
				fail(fmt.Errorf("side: %w", err))
				continue
			}
			tags.Side, tags.HasSide = side, true
		case tagType:
			tags.Type = value
		case tagPK:
			tags.PK = true
		case tagUnique:
			tags.Unique = true
		case tagIdentity:
			tags.HasIdentity = true
			switch value {
			case "", "default", "bydefault", "by_default":
				tags.Identity = model.IdentityByDefault
			case "always":
				tags.Identity = model.IdentityAlways
			default:
				fail(fmt.Errorf("identity: unknown kind %q; write identity or identity:always", value))
			}
		case tagDefault:
			tags.Default, tags.HasDefault = value, true
		case tagGenerated:
			tags.Generated = value
		case tagPGType:
			tags.PGType = value
		default:
			fail(fmt.Errorf("unknown directive %q; the tag grammar is column:, fk:, side:, type:, pk, identity, unique, default:, generated:, pgtype: and -", key))
		}
	}
	return tags, firstErr
}

// checkTagPlacement rejects directives that are meaningless on the kind of field
// they were written on.
//
// fk: and side: describe how a relation resolves against the catalog, so they
// say nothing on a scalar. column: and type: describe how a value is stored, so
// they say nothing on a relation — a relation occupies no column of its own.
func checkTagPlacement(tags model.FieldTags, isRelation bool) error {
	if tags.Ignore {
		return nil
	}
	var offenders []string
	if isRelation {
		if tags.Column != "" {
			offenders = append(offenders, "column:")
		}
		if tags.Type != "" {
			offenders = append(offenders, "type:")
		}
		if len(offenders) > 0 {
			return fmt.Errorf("%s is not valid on a relation field; a relation occupies no column of its own", strings.Join(offenders, " and "))
		}
		return nil
	}
	if tags.FK != "" {
		offenders = append(offenders, "fk:")
	}
	if tags.HasSide {
		offenders = append(offenders, "side:")
	}
	if len(offenders) > 0 {
		return fmt.Errorf("%s is only valid on an orm.One or orm.Many field", strings.Join(offenders, " and "))
	}
	return nil
}

// splitDirectives splits a tag on commas that are not inside parentheses or
// quotes, so that an SQL expression survives being written in one.
func splitDirectives(raw string) []string {
	var (
		out     []string
		depth   int
		inQuote bool
		start   int
	)
	for i := 0; i < len(raw); i++ {
		switch {
		case raw[i] == '\'':
			inQuote = !inQuote
		case inQuote:
		case raw[i] == '(':
			depth++
		case raw[i] == ')':
			depth--
		case raw[i] == ',' && depth == 0:
			out = append(out, raw[start:i])
			start = i + 1
		}
	}
	return append(out, raw[start:])
}
