// Adopting a database that already exists, and telling the three states apart.

// existing is a schema created the way any other tool would create it, with no
// involvement from this one.
const existing = `
CREATE TYPE post_status AS ENUM ('draft', 'published');

CREATE TABLE users (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      text NOT NULL UNIQUE,
    active     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE posts (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title     text NOT NULL,
    status    post_status NOT NULL DEFAULT 'draft',
    CONSTRAINT posts_title_not_blank CHECK (title <> '')
);

CREATE INDEX posts_author_idx ON posts (author_id, id DESC) INCLUDE (title) WHERE status = 'published';
`

func connect(t *testing.T, ddl string) *pgx.Conn {
	t.Helper()
	testdb.AdminDSN(t)
	conn, err := pgx.Connect(t.Context(), testdb.Create(t, ddl))
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.WithoutCancel(t.Context())) })
	return conn
}

func inspect(t *testing.T, conn *pgx.Conn) *schema.Schema {
	t.Helper()
	s, err := managed.Inspect(t.Context(), conn, []string{"public"})
	if err != nil {
		t.Fatalf("Inspect: %v", err)
	}
	return s
}

// Inspecting a database twice describes it the same way, so the result can be
// committed and diffed.
func TestInspect_isDeterministic(t *testing.T) {
	conn := connect(t, existing)

	first := inspect(t, conn)
	if len(first.Tables) != 2 || len(first.Enums) != 1 {
		t.Fatalf("inspected %d tables and %d enums", len(first.Tables), len(first.Enums))
	}
	var rendered bytes.Buffer
	if err := managed.Render(&rendered, first); err != nil {
		t.Fatalf("Render: %v", err)
	}
	for range 10 {
		again := inspect(t, conn)
		if diffs := schema.Diff(first, again); len(diffs) > 0 {
			t.Fatalf("inspection differs between runs:\n    %s", strings.Join(diffs, "\n    "))
		}
		var out bytes.Buffer
		if err := managed.Render(&out, again); err != nil {
			t.Fatalf("Render: %v", err)
		}
		if out.String() != rendered.String() {
			t.Fatal("the rendered schema differs between runs")
		}
	}
	// What it read is what is there, including the parts a simpler
	// introspection would drop.
	posts, _ := first.Table("public", "posts")
	if len(posts.Checks) != 1 || len(posts.Indexes) != 1 || len(posts.ForeignKeys) != 1 {
		t.Fatalf("posts = %+v", posts)
	}
	if posts.ForeignKeys[0].OnDelete != schema.Cascade {
		t.Errorf("on delete = %q, want CASCADE", posts.ForeignKeys[0].OnDelete)
	}
	idx := posts.Indexes[0]
	if len(idx.Columns) != 2 || idx.Columns[1].Direction != schema.Desc ||
		len(idx.Include) != 1 || idx.Where.Empty() {
		t.Errorf("index = %+v", idx)
	}
}

// The flagship database-first adoption: an existing database becomes a managed
// one without a single schema-changing statement.
func TestBaseline_adoptsAnExistingDatabase(t *testing.T) {
	conn := connect(t, existing)
	live := inspect(t, conn)

	base, err := managed.Baseline("0001_baseline", live)
	if err != nil {
		t.Fatalf("Baseline: %v", err)
	}
	set, err := migrate.NewSet([]*migrate.Migration{base})
	if err != nil {
		t.Fatalf("NewSet: %v", err)
	}

	// The baseline describes what is already there, so what it would create and
	// what exists are the same schema.
	state, err := set.State()
	if err != nil {
		t.Fatalf("State: %v", err)
	}
	if diffs := schema.Diff(state, live); len(diffs) > 0 {
		t.Fatalf("the baseline does not describe the live schema:\n    %s", strings.Join(diffs, "\n    "))
	}

	// Recorded as applied rather than run. Running it would try to create
	// tables that exist.
	m := migrate.New(conn, set)
	if _, err := m.MarkApplied(t.Context(), "0001_baseline"); err != nil {
		t.Fatalf("MarkApplied: %v", err)
	}
	applied, err := m.Applied(t.Context())
	if err != nil {
		t.Fatalf("Applied: %v", err)
	}
	if len(applied) != 1 || applied[0].ID != "0001_baseline" {
		t.Fatalf("history = %+v", applied)
	}
	sum, _ := set.Checksum("0001_baseline")
	if applied[0].Checksum != sum {
		t.Error("the baseline was recorded without its real checksum")
	}

	// The database is untouched.
	if diffs := schema.Diff(live, inspect(t, conn)); len(diffs) > 0 {
		t.Errorf("adopting the database changed it:\n    %s", strings.Join(diffs, "\n    "))
	}

	// And there is nothing to do.
	plan, err := m.Migrate(t.Context(), "")
	if err != nil {
		t.Fatalf("Migrate: %v", err)
	}
	if !plan.Empty() {
		t.Errorf("plan = %s, want nothing after adoption", plan.Describe())
	}
}

// After adoption, a change to the models produces only that change — not a
// second attempt to create everything.
func TestBaseline_thenIncrementalChange(t *testing.T) {
	conn := connect(t, existing)
	live := inspect(t, conn)

	base, err := managed.Baseline("0001_baseline", live)
	if err != nil {
		t.Fatalf("Baseline: %v", err)
	}
	set, err := migrate.NewSet([]*migrate.Migration{base})
	if err != nil {
		t.Fatalf("NewSet: %v", err)
	}
	m := migrate.New(conn, set)
	if _, err := m.MarkApplied(t.Context(), "0001_baseline"); err != nil {
		t.Fatalf("MarkApplied: %v", err)
	}

	// The desired schema gains a column and an enum label.
	next := live.Clone()
	for i := range next.Tables {
		if next.Tables[i].Name == "users" {
			next.Tables[i].Columns = append(next.Tables[i].Columns, schema.Column{
				Name: "nickname", Type: schema.Type{Name: "text"}, Nullable: true,
			})
		}
	}
	for i := range next.Enums {
		next.Enums[i].Labels = append(next.Enums[i].Labels, "archived")
	}
	next.Normalize()

	state, err := set.State()
	if err != nil {
		t.Fatalf("State: %v", err)
	}
	d, err := migrate.Compute(state, next, migrate.Options{})
	if err != nil {
		t.Fatalf("Compute: %v", err)
	}
	if len(d.Operations) != 2 {
		var got []string
		for _, op := range d.Operations {
			got = append(got, op.Describe())
		}
		t.Fatalf("operations = %v, want only the incremental change", got)
	}

	// Applied, it reaches the new schema — and nothing was recreated.
	set, err = migrate.NewSet([]*migrate.Migration{
		base,
		{ID: "0002_nickname", DependsOn: []string{"0001_baseline"}, Operations: d.Operations, Atomic: true},
	})
	if err != nil {
		t.Fatalf("NewSet: %v", err)
	}
	if _, err := migrate.New(conn, set).Migrate(t.Context(), ""); err != nil {
		t.Fatalf("Migrate: %v", err)
	}
	if diffs := schema.Diff(next, inspect(t, conn)); len(diffs) > 0 {
		t.Errorf("the database is not the new schema:\n    %s", strings.Join(diffs, "\n    "))
	}
}

// The three states answer three different questions, and a comparison that
// collapsed them would answer none.
func TestCompare_threeStates(t *testing.T) {
	users := func(cols ...schema.Column) *schema.Schema {
		s := &schema.Schema{Tables: []schema.Table{{
			Schema: "public", Name: "users", Columns: cols,
			PrimaryKey: &schema.PrimaryKey{Name: "users_pkey", Columns: []string{"id"}},
		}}}
		s.Normalize()
		return s
	}
	id := schema.Column{Name: "id", Type: schema.Type{Name: "int8"}, Identity: schema.IdentityByDefault}
	email := schema.Column{Name: "email", Type: schema.Type{Name: "text"}}
	status := schema.Column{Name: "status", Type: schema.Type{Name: "text"}, Nullable: true}

	s1 := users(id, email)
	s2 := users(id, email, status)

	first, err := migrate.Compute(&schema.Schema{}, s1, migrate.Options{})
	if err != nil {
		t.Fatalf("Compute: %v", err)
	}
	second, err := migrate.Compute(s1, s2, migrate.Options{})
	if err != nil {
		t.Fatalf("Compute: %v", err)
	}
	set, err := migrate.NewSet([]*migrate.Migration{
		{ID: "0001", Operations: first.Operations, Atomic: true},
		{ID: "0002", DependsOn: []string{"0001"}, Operations: second.Operations, Atomic: true},
	})
	if err != nil {
		t.Fatalf("NewSet: %v", err)
	}
	sum1, _ := set.Checksum("0001")
	sum2, _ := set.Checksum("0002")

	t.Run("everything agrees", func(t *testing.T) {
		c, err := managed.Compare(managed.CompareInput{
			Desired: s2, Set: set, Actual: s2,
			Applied: []migrate.Applied{{ID: "0001", Checksum: sum1}, {ID: "0002", Checksum: sum2}},
		})
		if err != nil {
			t.Fatalf("Compare: %v", err)
		}
		if c.NeedsMigration() || c.NeedsMigrate() || c.HasDrift() {
			t.Errorf("comparison = %s", c.Describe())
		}
	})

	t.Run("the models moved ahead of the migrations", func(t *testing.T) {
		s3 := users(id, email, status, schema.Column{Name: "extra", Type: schema.Type{Name: "text"}, Nullable: true})
		c, err := managed.Compare(managed.CompareInput{
			Desired: s3, Set: set, Actual: s2,
			Applied: []migrate.Applied{{ID: "0001", Checksum: sum1}, {ID: "0002", Checksum: sum2}},
		})
		if err != nil {
			t.Fatalf("Compare: %v", err)
		}
		if !c.NeedsMigration() {
			t.Error("a model change was not reported")
		}
		if c.NeedsMigrate() || c.HasDrift() {
			t.Errorf("a model change was also reported as pending work or drift:\n%s", c.Describe())
		}
	})

	t.Run("a migration has not been run", func(t *testing.T) {
		// The database is at 0001, which is exactly what its history says. That
		// is pending work and not drift, and calling it drift would train
		// people to ignore drift.
		c, err := managed.Compare(managed.CompareInput{
			Desired: s2, Set: set, Actual: s1,
			Applied: []migrate.Applied{{ID: "0001", Checksum: sum1}},
		})
		if err != nil {
			t.Fatalf("Compare: %v", err)
		}
		if !c.NeedsMigrate() || len(c.PendingMigrations) != 1 || c.PendingMigrations[0] != "0002" {
			t.Errorf("pending = %v", c.PendingMigrations)
		}
		if c.HasDrift() {
			t.Errorf("pending work was reported as drift:\n%s", c.Describe())
		}
		if c.NeedsMigration() {
			t.Errorf("pending work was reported as a model change:\n%s", c.Describe())
		}
	})

	t.Run("somebody changed the database", func(t *testing.T) {
		// History says both migrations ran, so the database should have the
		// status column. It does not.
		c, err := managed.Compare(managed.CompareInput{
			Desired: s2, Set: set, Actual: s1,
			Applied: []migrate.Applied{{ID: "0001", Checksum: sum1}, {ID: "0002", Checksum: sum2}},
		})
		if err != nil {
			t.Fatalf("Compare: %v", err)
		}
		if !c.HasDrift() {
			t.Error("a database changed behind the migrations was not reported as drift")
		}
		if c.NeedsMigrate() {
			t.Errorf("drift was reported as pending work:\n%s", c.Describe())
		}
		if !strings.Contains(c.Describe(), "differs from what its applied migrations describe") {
			t.Errorf("description does not name the problem:\n%s", c.Describe())
		}
	})

	t.Run("database mode declares no desired schema", func(t *testing.T) {
		c, err := managed.Compare(managed.CompareInput{
			Set: set, Actual: s2,
			Applied: []migrate.Applied{{ID: "0001", Checksum: sum1}, {ID: "0002", Checksum: sum2}},
		})
		if err != nil {
			t.Fatalf("Compare: %v", err)
		}
		if c.NeedsMigration() {
			t.Error("a model change was reported without any models")
		}
		if !strings.Contains(c.Describe(), "not declared") {
			t.Errorf("description = %s", c.Describe())
		}
	})
}
