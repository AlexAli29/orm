// Rendering schema objects as PostgreSQL DDL.
//
// Every identifier goes through the same quoter the query compiler uses, so
// there is one implementation of what quoting means and one place it can be
// wrong. Nothing here concatenates a bare name into a statement.
//
// Expressions are different, and deliberately so. DDL has no parameters —
// PostgreSQL does not accept DEFAULT $1 — so a default, a check condition and
// an index predicate are SQL text by necessity. They come from schema
// declarations a developer wrote and reviewed, never from anything a request
// carried, and the schema.Expr type exists to make every such place visible.

// ident quotes one identifier. A name that cannot be quoted — empty, or
// carrying a NUL — panics rather than producing a statement that means
// something else, because it can only arrive here from a generator bug.
func ident(name string) string {
	quoted, err := expr.QuoteIdentifier(name)
	if err != nil {
		panic("orm/migrate: " + err.Error())
	}
	return quoted
}

// qualified renders schema.table, omitting the schema when there is none.
func qualified(schemaName, name string) string {
	if schemaName == "" {
		return ident(name)
	}
	return ident(schemaName) + "." + ident(name)
}

// identList renders a parenthesised, comma-separated column list.
func identList(names []string) string {
	parts := make([]string, 0, len(names))
	for _, n := range names {
		parts = append(parts, ident(n))
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

// columnDefinition renders a column as it appears in CREATE TABLE or ADD
// COLUMN.
func columnDefinition(c schema.Column) (string, error) {
	if c.Name == "" {
		return "", fmt.Errorf("a column has no name")
	}
	if c.Type.Name == "" {
		return "", fmt.Errorf("column %s has no type", c.Name)
	}

	var b strings.Builder
	b.WriteString(ident(c.Name))
	b.WriteByte(' ')
	b.WriteString(c.Type.String())
	if c.Collation != "" {
		b.WriteString(" COLLATE ")
		b.WriteString(ident(c.Collation))
	}

	// A generated column defines its own value and cannot also have a default
	// or an identity, so the three are mutually exclusive here as they are in
	// PostgreSQL.
	switch {
	case !c.Generated.Empty():
		b.WriteString(" GENERATED ALWAYS AS (")
		b.WriteString(string(c.Generated))
		b.WriteString(") STORED")
	case c.Identity == schema.IdentityAlways:
		b.WriteString(" GENERATED ALWAYS AS IDENTITY")
	case c.Identity == schema.IdentityByDefault:
		b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
	case !c.Default.Empty():
		b.WriteString(" DEFAULT ")
		b.WriteString(string(c.Default))
	}
	if !c.Nullable {
		b.WriteString(" NOT NULL")
	}
	return b.String(), nil
}

// createTableSQL renders a table and the statements for anything on it that
// PostgreSQL will not accept inline.
func createTableSQL(t schema.Table) ([]string, error) {
	var parts []string
	for _, c := range t.Columns {
		def, err := columnDefinition(c)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", t.Qualified(), err)
		}
		parts = append(parts, "    "+def)
	}
	if len(parts) == 0 {
		return nil, fmt.Errorf("table %s has no columns", t.Qualified())
	}

	if pk := t.PrimaryKey; pk != nil {
		parts = append(parts, "    "+primaryKeyClause(*pk))
	}
	for _, u := range t.Uniques {
		// Only a UNIQUE constraint belongs inline. A bare unique index — and
		// any partial one — is a separate object and follows as CREATE INDEX.
		if !u.Constraint {
			continue
		}
		parts = append(parts, "    "+uniqueClause(u))
	}
	for _, c := range t.Checks {
		parts = append(parts, "    "+checkClause(c))
	}
	for _, f := range t.ForeignKeys {
		parts = append(parts, "    "+foreignKeyClause(f))
	}

	out := []string{
		"CREATE TABLE " + qualified(t.Schema, t.Name) + " (\n" + strings.Join(parts, ",\n") + "\n)",
	}
	for _, u := range t.Uniques {
		if u.Constraint {
			continue
		}
		// A unique index belongs in Indexes; this list holds constraints. A
		// schema that names the same object in both places would otherwise
		// build it twice, and the second statement would fail on a name the
		// first had taken.
		if slices.ContainsFunc(t.Indexes, func(i schema.Index) bool { return i.Name == u.Name }) {
			continue
		}
		out = append(out, uniqueIndexSQL(t, u))
	}
	for _, i := range t.Indexes {
		stmt, err := createIndexSQL(t.Schema, t.Name, i)
		if err != nil {
			return nil, err
		}
		out = append(out, stmt)
	}
	return out, nil
}

func primaryKeyClause(pk schema.PrimaryKey) string {
	s := ""
	if pk.Name != "" {
		s = "CONSTRAINT " + ident(pk.Name) + " "
	}
	return s + "PRIMARY KEY " + identList(pk.Columns)
}

func uniqueClause(u schema.Unique) string {
	s := ""
	if u.Name != "" {
		s = "CONSTRAINT " + ident(u.Name) + " "
	}
	s += "UNIQUE "
	if u.NullsNotDistinct {
		s += "NULLS NOT DISTINCT "
	}
	return s + identList(u.Columns)
}

func checkClause(c schema.Check) string {
	s := ""
	if c.Name != "" {
		s = "CONSTRAINT " + ident(c.Name) + " "
	}
	s += "CHECK (" + string(c.Expression) + ")"
	if c.NotValid {
		s += " NOT VALID"
	}
	return s
}

func foreignKeyClause(f schema.ForeignKey) string {
	var b strings.Builder
	if f.Name != "" {
		b.WriteString("CONSTRAINT " + ident(f.Name) + " ")
	}
	b.WriteString("FOREIGN KEY ")
	b.WriteString(identList(f.Columns))
	b.WriteString(" REFERENCES ")
	b.WriteString(qualified(f.RefSchema, f.RefTable))
	b.WriteString(identList(f.RefColumns))
	// NO ACTION is PostgreSQL's default. Rendering it anyway would make a
	// constraint that was never asked to change look changed.
	if f.OnDelete != "" && f.OnDelete != schema.NoAction {
		b.WriteString(" ON DELETE " + string(f.OnDelete))
	}
	if f.OnUpdate != "" && f.OnUpdate != schema.NoAction {
		b.WriteString(" ON UPDATE " + string(f.OnUpdate))
	}
	if f.Deferrable {
		b.WriteString(" DEFERRABLE")
		if f.InitiallyDeferred {
			b.WriteString(" INITIALLY DEFERRED")
		}
	}
	if f.NotValid {
		b.WriteString(" NOT VALID")
	}
	return b.String()
}

// uniqueIndexSQL renders a bare unique index, which is not a constraint.
func uniqueIndexSQL(t schema.Table, u schema.Unique) string {
	stmt := "CREATE UNIQUE INDEX " + ident(u.Name) + " ON " + qualified(t.Schema, t.Name) + " " + identList(u.Columns)
	if !u.Where.Empty() {
		stmt += " WHERE " + string(u.Where)
	}
	return stmt
}

// createIndexSQL renders one index.
func createIndexSQL(schemaName, table string, i schema.Index) (string, error) {
	if i.Name == "" {
		return "", fmt.Errorf("an index on %s.%s has no name", schemaName, table)
	}
	if len(i.Columns) == 0 {
		return "", fmt.Errorf("index %s has no columns", i.Name)
	}

	var b strings.Builder
	b.WriteString("CREATE ")
	if i.Unique {
		b.WriteString("UNIQUE ")
	}
	b.WriteString("INDEX ")
	if i.Concurrently {
		b.WriteString("CONCURRENTLY ")
	}
	b.WriteString(ident(i.Name))
	b.WriteString(" ON ")
	b.WriteString(qualified(schemaName, table))
	if i.Method != "" && !strings.EqualFold(i.Method, "btree") {
		b.WriteString(" USING " + ident(i.Method))
	}

	keys := make([]string, 0, len(i.Columns))
	for _, c := range i.Columns {
		key, err := indexKey(c)
		if err != nil {
			return "", fmt.Errorf("index %s: %w", i.Name, err)
		}
		keys = append(keys, key)
	}
	b.WriteString(" (" + strings.Join(keys, ", ") + ")")

	if len(i.Include) > 0 {
		b.WriteString(" INCLUDE " + identList(i.Include))
	}
	if !i.Where.Empty() {
		b.WriteString(" WHERE " + string(i.Where))
	}
	return b.String(), nil
}

// indexKey renders one key of an index: a column or an expression, with its
// operator class and sort order.
func indexKey(c schema.IndexColumn) (string, error) {
	var key string
	switch {
	case c.Name != "":
		key = ident(c.Name)
	case !c.Expression.Empty():
		// An expression key is parenthesised because PostgreSQL requires it for
		// anything that is not a bare column reference or a function call.
		key = "(" + string(c.Expression) + ")"
	default:
		return "", fmt.Errorf("an index key is neither a column nor an expression")
	}
	if c.OpClass != "" {
		key += " " + ident(c.OpClass)
	}
	if c.Direction == schema.Desc {
		key += " DESC"
	}
	switch c.Nulls {
	case schema.NullsFirst:
		key += " NULLS FIRST"
	case schema.NullsLast:
		key += " NULLS LAST"
	}
	return key, nil
}
