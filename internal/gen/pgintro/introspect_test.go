func TestIntrospect_columnFacts(t *testing.T) {
	s := introspect(t)
	users := table(t, s, "public.users")

	tests := []struct {
		col        string
		notNull    bool
		hasDefault bool
		identity   byte
		generated  byte
		typeName   string
	}{
		{col: "id", notNull: true, identity: 'd', typeName: "int8"},
		{col: "email", notNull: true, typeName: "public.email"},
		{col: "nick", typeName: "public.nickname"},
		{col: "state", notNull: true, hasDefault: true, typeName: "public.status"},
		{col: "tags", typeName: "text[]"},
		{col: "created_at", notNull: true, hasDefault: true, typeName: "timestamptz"},
	}
	for _, tt := range tests {
		t.Run(tt.col, func(t *testing.T) {
			c := users.Column(tt.col)
			if c == nil {
				t.Fatalf("column %s missing", tt.col)
			}
			if c.NotNull != tt.notNull {
				t.Errorf("NotNull = %v, want %v", c.NotNull, tt.notNull)
			}
			if c.HasDefault != tt.hasDefault {
				t.Errorf("HasDefault = %v, want %v", c.HasDefault, tt.hasDefault)
			}
			if c.Identity != tt.identity {
				t.Errorf("Identity = %q, want %q", c.Identity, tt.identity)
			}
			if c.Generated != tt.generated {
				t.Errorf("Generated = %q, want %q", c.Generated, tt.generated)
			}
			if got := c.Type.String(); got != tt.typeName {
				t.Errorf("type = %q, want %q", got, tt.typeName)
			}
		})
	}
}

func TestIntrospect_generatedColumnIsNotADefault(t *testing.T) {
	s := introspect(t)
	slug := table(t, s, "public.posts").Column("slug")
	if slug == nil {
		t.Fatal("slug missing")
	}
	if !slug.IsGenerated() {
		t.Error("slug is not reported as generated")
	}
	if slug.HasDefault {
		t.Error("a stored generated column reported HasDefault; the two facts must stay apart")
	}
	if slug.Writable() {
		t.Error("a stored generated column reported writable")
	}
}

func TestIntrospect_domainsAndNullability(t *testing.T) {
	s := introspect(t)
	users := table(t, s, "public.users")

	email := users.Column("email")
	if email.Type.Kind != model.PGDomain {
		t.Fatalf("email type kind = %v, want domain", email.Type.Kind)
	}
	if got := email.Type.Resolve().Name; got != "text" {
		t.Errorf("email resolves to %q, want text", got)
	}

	nick := users.Column("nick")
	if nick.NotNull {
		t.Fatal("nick is declared without NOT NULL")
	}
	if !nick.Nullable() {
		t.Error("nick.Nullable() = false; the nickname domain carries no NOT NULL")
	}
}

func TestIntrospect_notNullDomainMakesColumnNotNullable(t *testing.T) {
	// users.email is declared NOT NULL at the column too, so build the
	// interesting case directly: a column of a NOT NULL domain that carries no
	// NOT NULL of its own.
	const extra = `CREATE DOMAIN public.tight AS text NOT NULL;
CREATE TABLE public.tightrope (id bigint PRIMARY KEY, v public.tight);`
	dsn := testdb.Create(t, extra)
	conn := testdb.Connect(t, dsn)
	got, err := pgintro.Introspect(t.Context(), conn, []string{"public"})
	if err != nil {
		t.Fatalf("Introspect: %v", err)
	}
	v := table(t, got, "public.tightrope").Column("v")
	if v.NotNull {
		t.Fatal("the column itself is not declared NOT NULL; the domain is")
	}
	if v.Nullable() {
		t.Error("Nullable() = true for a column of a NOT NULL domain, want false")
	}
}

