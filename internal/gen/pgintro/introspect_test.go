const ddl = `
CREATE SCHEMA analytics;

CREATE TYPE public.status AS ENUM ('pending', 'active', 'banned');
CREATE DOMAIN public.email AS text NOT NULL;
CREATE DOMAIN public.nickname AS varchar(40);

CREATE TABLE public.users (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  bigint NOT NULL,
    email      public.email NOT NULL,
    nick       public.nickname,
    state      public.status NOT NULL DEFAULT 'pending',
    tags       text[],
    grid       int[][],
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, id)
);

CREATE TABLE public.profiles (
    id      bigserial PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES public.users(id),
    bio     text
);

CREATE TABLE public.posts (
    tenant_id bigint NOT NULL,
    id        bigint NOT NULL,
    author_id bigint,
    title     text NOT NULL,
    slug      text GENERATED ALWAYS AS (lower(title)) STORED,
    PRIMARY KEY (tenant_id, id),
    CONSTRAINT posts_author_fkey FOREIGN KEY (tenant_id, author_id)
        REFERENCES public.users(tenant_id, id) DEFERRABLE
);

CREATE UNIQUE INDEX posts_partial_slug ON public.posts (slug) WHERE slug IS NOT NULL;
CREATE UNIQUE INDEX posts_lower_title ON public.posts (lower(title));
CREATE UNIQUE INDEX posts_covering ON public.posts (author_id) INCLUDE (title);

CREATE VIEW public.active_users AS SELECT id FROM public.users;

CREATE TABLE analytics.events (
    id   bigserial PRIMARY KEY,
    name text NOT NULL
);
`

// The composite foreign key above pairs posts(tenant_id, author_id) with
// users(tenant_id, id). The two sides are deliberately not in the same relative
// column order on their tables, so an implementation that compared column sets
// instead of conkey and confkey ordinality would pair author_id with tenant_id
// and still look correct.

func introspect(t *testing.T, searchPath ...string) *model.Schema {
	t.Helper()
	dsn := testdb.Create(t, ddl)
	conn := testdb.Connect(t, dsn)
	if len(searchPath) == 0 {
		searchPath = []string{"public"}
	}
	schema, err := pgintro.Introspect(t.Context(), conn, searchPath)
	if err != nil {
		t.Fatalf("Introspect: %v", err)
	}
	return schema
}

func table(t *testing.T, s *model.Schema, name string) *model.PGTable {
	t.Helper()
	ref, err := model.ParseTableRef(name)
	if err != nil {
		t.Fatalf("ParseTableRef(%q): %v", name, err)
	}
	tbl, ok := s.Lookup(ref)
	if !ok {
		t.Fatalf("table %s not introspected", name)
	}
	return tbl
}

func TestIntrospect_tablesOnly(t *testing.T) {
	s := introspect(t)
	var names []string
	for _, tbl := range s.Tables {
		names = append(names, tbl.Qualified())
	}
	got := strings.Join(names, ",")
	const want = "public.posts,public.profiles,public.users"
	if got != want {
		t.Errorf("tables = %q, want %q (views and other schemas excluded)", got, want)
	}
}

