func TestIntrospect_compositeForeignKeyOrdinality(t *testing.T) {
	s := introspect(t)
	posts := table(t, s, "public.posts")
	var fk *model.PGForeignKey
	for _, f := range posts.FKs {
		if f.Name == "posts_author_fkey" {
			fk = f
		}
	}
	if fk == nil {
		t.Fatal("posts_author_fkey not introspected")
	}
	var local []string
	for _, c := range fk.Cols {
		local = append(local, c.Name)
	}
	if got := strings.Join(local, ","); got != "tenant_id,author_id" {
		t.Errorf("referencing columns = %q, want tenant_id,author_id in conkey order", got)
	}
	var remote []string
	for _, c := range fk.RefCols {
		remote = append(remote, c.Name)
	}
	// users declares id before tenant_id, so confkey order here is descending
	// by attribute number. Sorting either side would pair the wrong columns.
	if got := strings.Join(remote, ","); got != "tenant_id,id" {
		t.Errorf("referenced columns = %q, want tenant_id,id in confkey order", got)
	}
	if len(fk.RefCols) != len(fk.Cols) {
		t.Fatalf("%d referencing columns against %d referenced", len(fk.Cols), len(fk.RefCols))
	}
	if fk.RefTable.Name != "users" {
		t.Errorf("referenced table = %q, want users", fk.RefTable.Name)
	}
}

func TestIntrospect_uniqueIndexClassification(t *testing.T) {
	s := introspect(t)
	posts := table(t, s, "public.posts")

	byName := make(map[string]model.PGUnique, len(posts.Uniques))
	for _, u := range posts.Uniques {
		byName[u.Name] = u
	}

	partial, ok := byName["posts_partial_slug"]
	if !ok {
		t.Fatal("posts_partial_slug not introspected")
	}
	if !partial.Partial {
		t.Error("a WHERE-qualified unique index was not marked partial")
	}
	if partial.Total() {
		t.Error("a partial unique index reported Total(); it proves nothing about rows it excludes")
	}

	expr, ok := byName["posts_lower_title"]
	if !ok {
		t.Fatal("posts_lower_title not introspected")
	}
	if !expr.Expression {
		t.Error("an expression unique index was not marked as such")
	}
	if expr.Total() {
		t.Error("an expression unique index reported Total()")
	}

	covering, ok := byName["posts_covering"]
	if !ok {
		t.Fatal("posts_covering not introspected")
	}
	if len(covering.Cols) != 1 || covering.Cols[0].Name != "author_id" {
		t.Errorf("covering index columns = %v, want the key column only, without the INCLUDE column", covering.Cols)
	}
	if !covering.Total() {
		t.Error("a plain unique index with an INCLUDE clause should still prove uniqueness")
	}

	pk, ok := byName["posts_pkey"]
	if !ok {
		t.Fatal("posts_pkey not introspected")
	}
	if !pk.Primary || !pk.Total() {
		t.Errorf("primary key index = %+v, want Primary and Total", pk)
	}
}

func TestIntrospect_uniqueConstraintIsProof(t *testing.T) {
	s := introspect(t)
	profiles := table(t, s, "public.profiles")
	var found bool
	for _, u := range profiles.Uniques {
		if u.Total() && len(u.Cols) == 1 && u.Cols[0].Name == "user_id" {
			found = true
		}
	}
	if !found {
		t.Error("the UNIQUE constraint on profiles.user_id was not recorded as a total unique index")
	}
}

func TestIntrospect_deterministicOrdering(t *testing.T) {
	dsn := testdb.Create(t, ddl)
	conn := testdb.Connect(t, dsn)

	render := func() string {
		s, err := pgintro.Introspect(t.Context(), conn, []string{"public", "analytics"})
		if err != nil {
			t.Fatalf("Introspect: %v", err)
		}
		var b strings.Builder
		for _, tbl := range s.Tables {
			fmt.Fprintf(&b, "%s\n", tbl.Qualified())
			for _, c := range tbl.Cols {
				fmt.Fprintf(&b, "  col %s %s\n", c.Name, c.Type)
			}
			for _, fk := range tbl.FKs {
				fmt.Fprintf(&b, "  fk %s\n", fk.Name)
			}
			for _, u := range tbl.Uniques {
				fmt.Fprintf(&b, "  uq %s\n", u.Name)
			}
		}
		return b.String()
	}

	first := render()
	for i := range 2 {
		if got := render(); got != first {
			t.Fatalf("introspection run %d differed from the first", i+2)
		}
	}
}

func TestFromFile(t *testing.T) {
	adminDSN := testdb.AdminDSN(t)
	dir := t.TempDir()
	path := filepath.Join(dir, "schema.sql")
	if err := os.WriteFile(path, []byte(ddl), 0o600); err != nil {
		t.Fatalf("writing the schema file: %v", err)
	}

	s, err := pgintro.FromFile(t.Context(), adminDSN, path, []string{"public"})
	if err != nil {
		t.Fatalf("FromFile: %v", err)
	}
	if len(s.Tables) != 3 {
		t.Errorf("introspected %d tables, want 3", len(s.Tables))
	}
	if _, ok := s.Lookup(model.TableRef{Schema: "public", Name: "users"}); !ok {
		t.Error("public.users missing from a schema built from a file")
	}
}

func TestFromFile_badDDLDropsTheTemporaryDatabase(t *testing.T) {
	adminDSN := testdb.AdminDSN(t)
	dir := t.TempDir()
	path := filepath.Join(dir, "schema.sql")
	if err := os.WriteFile(path, []byte("CREATE TABLE ( oops"), 0o600); err != nil {
		t.Fatalf("writing the schema file: %v", err)
	}

	_, err := pgintro.FromFile(t.Context(), adminDSN, path, []string{"public"})
	if err == nil {
		t.Fatal("FromFile succeeded on invalid DDL")
	}
	if !strings.Contains(err.Error(), "applying") {
		t.Errorf("error = %v, want it to name the failing step", err)
	}

	conn := testdb.Connect(t, adminDSN)
	var leftovers int
	row := conn.QueryRow(t.Context(), `SELECT count(*) FROM pg_database WHERE datname LIKE 'orm_check_%'`)
	if err := row.Scan(&leftovers); err != nil {
		t.Fatalf("counting temporary databases: %v", err)
	}
	if leftovers != 0 {
		t.Errorf("%d temporary databases left behind after a DDL failure", leftovers)
	}
}
