// M16.5: reading views and materialized views out of the catalog.
//
// Every assertion here is against a real PostgreSQL, because the catalog is the
// only authority for what a relation is. Nothing infers a kind from a name.

const viewSchema = `
CREATE TABLE users (
	id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email       text NOT NULL,
	active      boolean NOT NULL,
	created_at  timestamptz NOT NULL DEFAULT now(),
	tags        text[] NOT NULL DEFAULT '{}',
	settings    jsonb NOT NULL DEFAULT '{}',
	last_ip     inet
);
CREATE TABLE orders (
	id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id  bigint NOT NULL REFERENCES users(id),
	price    numeric NOT NULL
);

CREATE VIEW active_users AS
	SELECT id, email, created_at, tags, settings, last_ip
	FROM users
	WHERE active;

-- A view on a view, so the dependency graph has a second level.
CREATE VIEW recent_active_users AS
	SELECT id, email, created_at FROM active_users
	WHERE created_at > now() - interval '30 days';

-- The nullability case that matters: price is NOT NULL on its table and can
-- still be SQL NULL here, because the outer join invents rows.
CREATE VIEW user_orders AS
	SELECT u.id AS user_id, u.email, o.price
	FROM users u
	LEFT JOIN orders o ON o.user_id = u.id;

CREATE MATERIALIZED VIEW user_totals AS
	SELECT u.id AS user_id, count(o.id) AS orders, sum(o.price) AS total
	FROM users u LEFT JOIN orders o ON o.user_id = u.id
	GROUP BY u.id
	WITH DATA;
CREATE UNIQUE INDEX user_totals_user_id_key ON user_totals (user_id);
CREATE INDEX user_totals_total_idx ON user_totals (total) WHERE total > 0;

CREATE MATERIALIZED VIEW empty_totals AS
	SELECT id FROM users WITH NO DATA;

-- SELECT * is the clearest proof that what comes back is a reconstruction:
-- PostgreSQL expands the star at definition time and can never return it.
CREATE VIEW everything AS SELECT * FROM users;

CREATE VIEW guarded AS SELECT id FROM users;
ALTER VIEW guarded SET (security_barrier = true);
`

func introspectViews(t *testing.T) *model.Schema {
	t.Helper()
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, viewSchema)
	conn, err := pgintro.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.Background()) })
	s, err := pgintro.Introspect(t.Context(), conn, []string{"public"})
	if err != nil {
		t.Fatalf("introspecting: %v", err)
	}
	return s
}

func find(t *testing.T, s *model.Schema, name string) *model.PGTable {
	t.Helper()
	for _, v := range s.Views {
		if v.Name == name {
			return v
		}
	}
	t.Fatalf("no view named %s; found %v", name, names(s.Views))
	return nil
}

func names(ts []*model.PGTable) []string {
	var out []string
	for _, t := range ts {
		out = append(out, t.Name)
	}
	return out
}

// Views are not tables, and the separation is structural rather than a flag.
func TestIntrospect_viewsAreNotTables(t *testing.T) {
	s := introspectViews(t)

	if got := names(s.Tables); len(got) != 2 {
		t.Errorf("tables = %v, want just users and orders", got)
	}
	for _, tb := range s.Tables {
		if tb.IsView() {
			t.Errorf("%s is in Tables and reports itself a view", tb.Name)
		}
		if !tb.Writable() {
			t.Errorf("%s is a table and is not writable", tb.Name)
		}
	}
	want := map[string]byte{
		"active_users": 'v', "recent_active_users": 'v', "user_orders": 'v', "guarded": 'v',
		"everything":  'v',
		"user_totals": 'm', "empty_totals": 'm',
	}
	if len(s.Views) != len(want) {
		t.Errorf("views = %v, want %d", names(s.Views), len(want))
	}
	for _, v := range s.Views {
		if want[v.Name] != v.Kind {
			t.Errorf("%s has relkind %q, want %q", v.Name, v.Kind, want[v.Name])
		}
		if v.Writable() {
			t.Errorf("%s is a view and reports itself writable", v.Name)
		}
	}
}

// A view's columns are ordinary columns, resolved through the same type
// machinery a table's columns are.
func TestIntrospect_viewColumnsKeepPostgreSQLTypes(t *testing.T) {
	v := find(t, introspectViews(t), "active_users")

	want := []struct{ name, pgType string }{
		{"id", "int8"}, {"email", "text"}, {"created_at", "timestamptz"},
		{"tags", "_text"}, {"settings", "jsonb"}, {"last_ip", "inet"},
	}
	if len(v.Cols) != len(want) {
		t.Fatalf("columns = %d, want %d", len(v.Cols), len(want))
	}
	for i, w := range want {
		c := v.Cols[i]
		if c.Name != w.name {
			t.Errorf("column %d is %s, want %s (order is meaning)", i, c.Name, w.name)
		}
		if c.Type == nil || c.Type.Name != w.pgType {
			t.Errorf("%s has type %v, want %s: a view must not degrade a "+
				"PostgreSQL-native type because the source kind changed", c.Name, c.Type, w.pgType)
		}
	}
}

// The definition is PostgreSQL's reconstruction and is treated as such.
func TestIntrospect_definitionComesFromTheServer(t *testing.T) {
	s := introspectViews(t)
	v := find(t, s, "active_users")
	if v.Definition == "" {
		t.Fatal("the view has no definition")
	}
	if !strings.Contains(v.Definition, "users") || !strings.Contains(v.Definition, "SELECT") {
		t.Errorf("the definition does not look like the reconstructed SELECT:\n%s", v.Definition)
	}

	// The proof that this is a reconstruction rather than the text somebody
	// typed: PostgreSQL expands * when the view is defined and can never give
	// it back. Anything comparing a project's own SQL against this byte for
	// byte would report drift on a view nobody had touched.
	star := find(t, s, "everything")
	if strings.Contains(star.Definition, "*") {
		t.Errorf("SELECT * survived into the definition, so this is not the "+
			"reconstruction pg_get_viewdef documents:\n%s", star.Definition)
	}
	for _, col := range []string{"email", "active", "settings"} {
		if !strings.Contains(star.Definition, col) {
			t.Errorf("the reconstructed definition of a SELECT * view does not name %s:\n%s",
				col, star.Definition)
		}
	}
	m := find(t, s, "user_totals")
	if m.Definition == "" {
		t.Error("a materialized view has no definition; pg_get_viewdef covers both kinds")
	}
}

// Dependencies come from the catalog, are relations only, and reach two levels.
func TestIntrospect_dependenciesAreRelationsOnly(t *testing.T) {
	s := introspectViews(t)

	deps := func(name string) []string {
		var out []string
		for _, d := range find(t, s, name).DependsOn {
			out = append(out, d.Schema+"."+d.Name)
		}
		return out
	}
	if got := deps("active_users"); len(got) != 1 || got[0] != "public.users" {
		t.Errorf("active_users depends on %v, want [public.users]", got)
	}
	// A view on a view: the edge is to the view, not flattened to the table.
	if got := deps("recent_active_users"); len(got) != 1 || got[0] != "public.active_users" {
		t.Errorf("recent_active_users depends on %v, want [public.active_users]", got)
	}
	if got := deps("user_orders"); len(got) != 2 {
		t.Errorf("user_orders depends on %v, want both users and orders", got)
	}
	// The kind travels with the edge, so ordering knows what it is waiting for.
	for _, d := range find(t, s, "recent_active_users").DependsOn {
		if d.Kind != 'v' {
			t.Errorf("the dependency on %s has kind %q, want v", d.Name, d.Kind)
		}
	}
	// Nothing but relations. A view depends on its own rule, its column types
	// and its owner too; treating those as edges would put nonsense in the order.
	for _, v := range s.Views {
		for _, d := range v.DependsOn {
			if d.Name == v.Name && d.Schema == v.Schema {
				t.Errorf("%s depends on itself", v.Name)
			}
			if !strings.ContainsRune("rpvmf", rune(d.Kind)) {
				t.Errorf("%s has a dependency of kind %q, which is not a relation", v.Name, d.Kind)
			}
		}
	}
}

// Population state is read, and is runtime state rather than schema identity.
func TestIntrospect_populatedState(t *testing.T) {
	s := introspectViews(t)
	if m := find(t, s, "user_totals"); !m.Populated {
		t.Error("a materialized view created WITH DATA reports itself unpopulated")
	}
	if m := find(t, s, "empty_totals"); m.Populated {
		t.Error("a materialized view created WITH NO DATA reports itself populated; " +
			"it is not scannable until something refreshes it")
	}
}

// View options are carried rather than dropped.
func TestIntrospect_viewOptionsSurvive(t *testing.T) {
	v := find(t, introspectViews(t), "guarded")
	var found bool
	for _, o := range v.Options {
		if o.Name == "security_barrier" {
			found = true
		}
	}
	if !found {
		t.Errorf("security_barrier was dropped on the way through introspection; "+
			"options were %v. Reading a view and writing it back without its options "+
			"silently changes a security boundary", v.Options)
	}
}

// Release-critical: a view column's nullability must never be more optimistic
// than PostgreSQL can justify.
//
// user_orders.price comes from orders.price, which is NOT NULL on its table.
// Through the LEFT JOIN it is nullable anyway: the join invents a row of nulls
// for every user with no order. A generator that carried the base column's NOT
// NULL across would produce a non-nullable Go field that receives SQL NULL on
// the first user who has never ordered.
//
// PostgreSQL does not record NOT NULL on view columns at all, which is the
// honest answer — it cannot prove nullability through arbitrary SQL either.
// This asserts that the introspection keeps that answer rather than improving
// on it, and it also queries the view to show the null is real.
func TestIntrospect_viewColumnsAreNotFalselyNotNull(t *testing.T) {
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, viewSchema+
		`INSERT INTO users (email, active) VALUES ('nobody@example.com', true);`)
	conn, err := pgintro.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.Background()) })
	s, err := pgintro.Introspect(t.Context(), conn, []string{"public"})
	if err != nil {
		t.Fatalf("introspecting: %v", err)
	}

	// The base column really is NOT NULL, so this test is about the view.
	var baseNotNull bool
	for _, tb := range s.Tables {
		if tb.Name != "orders" {
			continue
		}
		for _, c := range tb.Cols {
			if c.Name == "price" {
				baseNotNull = c.NotNull
			}
		}
	}
	if !baseNotNull {
		t.Fatal("orders.price is not NOT NULL on its table, so this test proves nothing")
	}

	for _, c := range find(t, s, "user_orders").Cols {
		if c.NotNull {
			t.Errorf("the view column %s is NOT NULL. Through a LEFT JOIN it can be "+
				"SQL NULL whatever its base column says, and a non-nullable Go field "+
				"would fail on the first row the join invents", c.Name)
		}
	}

	// And the null is not hypothetical.
	var price *string
	if err := conn.QueryRow(t.Context(),
		`SELECT price::text FROM user_orders WHERE email = 'nobody@example.com'`).Scan(&price); err != nil {
		t.Fatalf("reading the view: %v", err)
	}
	if price != nil {
		t.Errorf("price = %q, want NULL", *price)
	}
}

// A materialized view's indexes are ordinary indexes, and the one that permits
// REFRESH CONCURRENTLY is exactly the one PostgreSQL's rules allow.
func TestIntrospect_materializedViewIndexes(t *testing.T) {
	m := find(t, introspectViews(t), "user_totals")
	if !m.IsMaterialized() {
		t.Fatal("user_totals is not reported as a materialized view")
	}
	var plainUnique int
	for _, u := range m.Uniques {
		if u.Partial || u.Expression {
			continue
		}
		plainUnique++
	}
	if plainUnique == 0 {
		t.Errorf("the unique index on a materialized view was not read; uniques were %v. "+
			"That index is what REFRESH CONCURRENTLY requires, so losing it makes every "+
			"concurrent refresh look impossible", m.Uniques)
	}

	// An ordinary view carries no indexes, and asking for them is not an error.
	if v := find(t, introspectViews(t), "active_users"); len(v.Uniques) != 0 {
		t.Errorf("an ordinary view reported indexes: %v", v.Uniques)
	}
}

// An extension's own relations are not the project's schema.
//
// PostGIS installs geometry_columns and geography_columns as views in the
// search path. Before views were introspected they never appeared; the moment
// they did, they arrived as project relations — which would mean generating
// query sources for PostGIS's catalog and, worse, letting a migration planner
// consider them. pg_depend is the catalog's own answer to what belongs to an
// extension, and it is the one this asks.
func TestIntrospect_extensionRelationsAreNotTheProjectsSchema(t *testing.T) {
	testdb.AdminDSN(t)
	var ok bool
	probe := testdb.Create(t, "")
	conn0, err := pgintro.Connect(t.Context(), probe)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	if err := conn0.QueryRow(t.Context(),
		`SELECT exists (SELECT 1 FROM pg_available_extensions WHERE name = 'postgis')`).Scan(&ok); err != nil {
		t.Fatalf("asking about PostGIS: %v", err)
	}
	_ = conn0.Close(context.Background())
	if !ok {
		t.Skip("this PostgreSQL has no PostGIS, which is the extension that installs views")
	}

	dsn := testdb.Create(t, `
		CREATE EXTENSION postgis;
		CREATE TABLE places (id bigint PRIMARY KEY, geom geometry(Point, 4326));
		CREATE VIEW mine AS SELECT id FROM places;
	`)
	conn, err := pgintro.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.Background()) })
	s, err := pgintro.Introspect(t.Context(), conn, []string{"public"})
	if err != nil {
		t.Fatalf("introspecting: %v", err)
	}

	for _, v := range s.Views {
		if v.Name == "geometry_columns" || v.Name == "geography_columns" {
			t.Errorf("%s belongs to PostGIS and was read as part of the project's schema", v.Name)
		}
	}
	var found bool
	for _, v := range s.Views {
		if v.Name == "mine" {
			found = true
		}
	}
	if !found {
		t.Errorf("the project's own view was excluded along with the extension's: %v", names(s.Views))
	}
}

// The deparser is not stable across PostgreSQL majors, and the contract depends
// on knowing that.
//
// PostgreSQL 16 stopped qualifying columns that need no qualification, so the
// same view reads "SELECT xt.id FROM xt" on 14 and 15 and "SELECT id FROM xt"
// on 16 and later. Nothing about the view changed.
//
// This is why canonical text compares a database against the project and never
// enters anything committed: an identical project would otherwise produce
// different locks on different servers, and switching between two supported
// majors would look like a schema change.
//
// The test records what this server does rather than asserting one spelling, so
// it documents the behaviour on whichever major it runs against and fails if
// the definition stops round-tripping at all.
func TestIntrospect_canonicalTextIsPerServer(t *testing.T) {
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, `
		CREATE TABLE xt (id bigint PRIMARY KEY, email text NOT NULL, active boolean NOT NULL);
		CREATE VIEW xv AS SELECT id, email FROM xt WHERE active;
	`)
	conn, err := pgintro.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.Background()) })
	s, err := pgintro.Introspect(t.Context(), conn, []string{"public"})
	if err != nil {
		t.Fatalf("introspecting: %v", err)
	}

	var num int
	if err := conn.QueryRow(t.Context(),
		`SELECT current_setting('server_version_num')::int`).Scan(&num); err != nil {
		t.Fatal(err)
	}
	def := find(t, s, "xv").Definition
	t.Logf("PostgreSQL %d deparses the view as:\n%s", num/10000, def)

	// Whatever the spelling, the definition is there and names what it reads.
	for _, want := range []string{"SELECT", "id", "email", "xt", "active"} {
		if !strings.Contains(def, want) {
			t.Errorf("the deparsed definition does not contain %q:\n%s", want, def)
		}
	}
	// And the qualification rule is the one this major is documented to use.
	qualified := strings.Contains(def, "xt.id")
	if num >= 160000 && qualified {
		t.Errorf("PostgreSQL %d qualified a column the deparser stopped qualifying in 16:\n%s", num/10000, def)
	}
	if num < 160000 && !qualified {
		t.Errorf("PostgreSQL %d did not qualify a column its deparser always qualified:\n%s", num/10000, def)
	}
}
