// Package schema is the canonical description of a PostgreSQL schema.
//
// It is the one representation three different questions are asked about:
//
//	what the models describe        (desired state)
//	what the migrations built up to (migration state)
//	what the database actually has  (introspected state)
//
// Migration diffing is only meaningful because all three are the same shape. A
// diff between a desired schema and a migration state, and a drift check between
// a migration state and a live database, are then the same comparison over the
// same types rather than two subsystems each inventing their own idea of what a
// column is.
//
// Everything here is PostgreSQL's own vocabulary. There is no portable
// abstraction underneath: a partial index, an INCLUDE column, an identity
// column and a NOT VALID constraint are the reasons to use PostgreSQL, and a
// representation that could also describe MySQL would have to drop all of them.
//
// The types are values with no pointers between objects, so a state can be
// copied, mutated by an operation and compared without anything aliasing
// anything else.
package schema

import (
	"cmp"
	"slices"
	"strings"
)

// Schema is a whole desired or actual schema.
type Schema struct {
	// Extensions are the PostgreSQL extensions the schema requires, sorted by
	// name. Nothing is installed implicitly because a type or a default happens
	// to mention one.
	Extensions []Extension
	// Enums are the enum types, sorted by qualified name.
	Enums []Enum
	// Tables are the tables, sorted by qualified name.
	Tables []Table
	// Views are the ordinary views, sorted by qualified name.
	Views []View
	// MaterializedViews are the materialized views, sorted by qualified name.
	MaterializedViews []MaterializedView
}

// Relation returns what a qualified name refers to, and whether the schema has
// it at all.
//
// One name is one relation in PostgreSQL — a schema cannot hold a table and a
// view called the same thing — so this is the question a caller should ask
// rather than searching three slices and hoping only one answers. It is also
// what makes a change of kind under one name detectable instead of appearing as
// an unrelated drop and create.
func (s *Schema) Relation(schemaName, name string) (RelationKind, bool) {
	for _, t := range s.Tables {
		if t.Schema == schemaName && t.Name == name {
			return KindTable, true
		}
	}
	for _, v := range s.Views {
		if v.Schema == schemaName && v.Name == name {
			return KindView, true
		}
	}
	for _, m := range s.MaterializedViews {
		if m.Schema == schemaName && m.Name == name {
			return KindMaterializedView, true
		}
	}
	return KindTable, false
}

// Extension is a required PostgreSQL extension.
type Extension struct {
	Name string
	// Schema is where the extension's objects live, empty for the default.
	Schema string
}

// Enum is a PostgreSQL enum type.
//
// Labels are in declaration order, which is the order PostgreSQL sorts them in.
// The order is part of the type's meaning, so it is never sorted here.
type Enum struct {
	Schema string
	Name   string
	Labels []string
}

// Qualified renders the enum as schema.name.
func (e Enum) Qualified() string { return e.Schema + "." + e.Name }

// Table is one table and everything declared on it.
type Table struct {
	Schema string
	Name   string
	// Columns are in the order the table declares them. Order is meaning: it
	// decides what SELECT * returns and what a positional scan reads.
	Columns []Column
	// PrimaryKey is nil when the table has none.
	PrimaryKey *PrimaryKey
	// The rest are sorted by name, because a constraint's position among its
	// siblings means nothing.
	Uniques     []Unique
	ForeignKeys []ForeignKey
	Checks      []Check
	Indexes     []Index
}

// Qualified renders the table as schema.name.
func (t Table) Qualified() string { return t.Schema + "." + t.Name }

// Column returns the named column and whether it exists.
func (t Table) Column(name string) (Column, bool) {
	for _, c := range t.Columns {
		if c.Name == name {
			return c, true
		}
	}
	return Column{}, false
}

// Identity says how PostgreSQL supplies a column's value for itself.
type Identity uint8

const (
	// NotIdentity is an ordinary column.
	NotIdentity Identity = iota
	// IdentityAlways is GENERATED ALWAYS AS IDENTITY: PostgreSQL refuses a
	// value unless overridden.
	IdentityAlways
	// IdentityByDefault is GENERATED BY DEFAULT AS IDENTITY.
	IdentityByDefault
)

func (i Identity) String() string {
	switch i {
	case IdentityAlways:
		return "always"
	case IdentityByDefault:
		return "by default"
	default:
		return ""
	}
}

// Column is one column's complete state.
//
// Everything here participates in diffing. A representation of name and type
// alone would report two columns as equal when one of them is nullable and the
// other is not, which is the difference between a migration that works and one
// that fails on the first row.
type Column struct {
	Name string
	// Type is the PostgreSQL type, written as PostgreSQL writes it: int8,
	// timestamptz, text[], public.user_state. Nothing here is a portable name.
	Type Type
	// Nullable reports a column that accepts NULL.
	Nullable bool
	// Default is the DEFAULT expression, empty when there is none. It is SQL,
	// not a value: now() and 'now()' are different things.
	Default Expr
	// Identity says whether PostgreSQL supplies the value.
	Identity Identity
	// Generated is the expression of a stored generated column, empty when the
	// column is not one.
	Generated Expr
	// Collation is the column's collation, empty for the default.
	Collation string
}

// Type is a PostgreSQL type reference.
//
// It is a name rather than a resolved catalog entry because a desired schema
// names types that may not exist yet. Resolution belongs to the database.
type Type struct {
	// Schema qualifies a type the schema itself declares — an enum, a domain.
	// It is empty for a built-in, which is how int8 and public.user_state stay
	// distinguishable without a catalog lookup.
	Schema string
	Name   string
	// Array reports a one-dimensional array of the named type.
	Array bool
}

// canonicalTypeNames maps the spellings PostgreSQL accepts and renders to the
// internal name it stores.
//
// The catalog keeps int8 and renders "bigint"; a declaration may say either.
// They are the same type, and a comparison that said otherwise would report a
// change on a column nobody touched — the churn that makes a migration tool
// untrustworthy.
var canonicalTypeNames = map[string]string{
	"bigint":                      "int8",
	"bigserial":                   "int8",
	"boolean":                     "bool",
	"character":                   "bpchar",
	"character varying":           "varchar",
	"double precision":            "float8",
	"integer":                     "int4",
	"int":                         "int4",
	"real":                        "float4",
	"serial":                      "int4",
	"smallint":                    "int2",
	"smallserial":                 "int2",
	"decimal":                     "numeric",
	"time with time zone":         "timetz",
	"time without time zone":      "time",
	"timestamp with time zone":    "timestamptz",
	"timestamp without time zone": "timestamp",
}

// Canonical returns the type under PostgreSQL's own internal name, so that two
// spellings of one type compare equal.
//
// A type carrying a modifier — varchar(255), numeric(10,2) — keeps it: the
// modifier is part of what the column accepts, not a spelling.
func (t Type) Canonical() Type {
	base, mod, hasMod := strings.Cut(t.Name, "(")
	name := strings.ToLower(strings.TrimSpace(base))
	if c, ok := canonicalTypeNames[name]; ok {
		name = c
	}
	if hasMod {
		name += "(" + canonicalModifier(name, mod)
	}
	t.Name = name
	return t
}

// canonicalModifier normalises a type modifier whose spelling PostgreSQL does
// not normalise for us.
//
// For most types the modifier is numbers — varchar(255), numeric(10,2) — and
// there is one way to write it. A spatial modifier is a shape name, and PostGIS
// accepts POINT, Point and point for the same column while format_type renders
// exactly one of them. Left alone, a declaration written in the other case
// would differ from the catalog forever, which is a migration generated on
// every run for a column nobody touched.
func canonicalModifier(base, mod string) string {
	if base != "geometry" && base != "geography" {
		return mod
	}
	body, closed := strings.CutSuffix(strings.TrimSpace(mod), ")")
	if !closed {
		return mod
	}
	parts := strings.Split(body, ",")
	for i := range parts {
		parts[i] = strings.TrimSpace(parts[i])
	}
	if len(parts) > 0 {
		parts[0] = canonicalShape(parts[0])
	}
	return strings.Join(parts, ",") + ")"
}

// spatialShapes maps a shape name folded to lower case to the spelling PostGIS
// renders, which is the one the canonical model keeps.
var spatialShapes = map[string]string{
	"geometry": "Geometry", "point": "Point", "linestring": "LineString",
	"polygon": "Polygon", "multipoint": "MultiPoint",
	"multilinestring": "MultiLineString", "multipolygon": "MultiPolygon",
	"geometrycollection": "GeometryCollection",
	"circularstring":     "CircularString", "compoundcurve": "CompoundCurve",
	"curvepolygon": "CurvePolygon", "multicurve": "MultiCurve",
	"multisurface": "MultiSurface", "polyhedralsurface": "PolyhedralSurface",
	"triangle": "Triangle", "tin": "Tin",
}

func canonicalShape(shape string) string {
	lower := strings.ToLower(shape)
	// The dimensionality suffix is part of the name — PointZM is one shape name
	// to PostGIS — so it is split off, the base is normalised, and the suffix is
	// written back in PostGIS's own upper case.
	for _, suffix := range []string{"zm", "z", "m"} {
		if base, ok := strings.CutSuffix(lower, suffix); ok {
			if canonical, known := spatialShapes[base]; known {
				return canonical + strings.ToUpper(suffix)
			}
		}
	}
	if canonical, ok := spatialShapes[lower]; ok {
		return canonical
	}
	return shape
}

// String renders the type as it appears in DDL.
func (t Type) String() string {
	name := t.Name
	if t.Schema != "" {
		name = t.Schema + "." + t.Name
	}
	if t.Array {
		name += "[]"
	}
	return name
}

// Expr is a fragment of schema SQL: a default, a check condition, an index
// predicate.
//
// It is deliberately a distinct type from a string. These are the one place in
// this project where SQL text ends up in a statement without being a parameter,
// because DDL has no parameters — DEFAULT $1 is not a thing PostgreSQL accepts.
// Naming the type makes every such place greppable, and makes it obvious that
// nothing built from user input belongs here.
type Expr string

// Empty reports whether there is no expression.
func (e Expr) Empty() bool { return strings.TrimSpace(string(e)) == "" }

// PrimaryKey is a table's primary key.
type PrimaryKey struct {
	Name string
	// Columns are in constraint order, which decides the index's usefulness and
	// is never sorted.
	Columns []string
}

// Unique is a uniqueness object on a table.
//
// In a schema this package's producers build, it is always a UNIQUE
// constraint: a unique index lives in [Table.Indexes] with Unique set, which is
// the one place an index of any kind is described. Recording a unique index in
// both was how the desired schema and the introspected one came to disagree
// about where the same object lived, and how one CREATE TABLE came to build it
// twice.
//
// Constraint is still part of the type, because PostgreSQL genuinely
// distinguishes the two — a constraint owns an index and is dropped through
// ALTER TABLE, an index is dropped through DROP INDEX, and only a constraint
// can be a foreign key's target — and a hand-written schema may say either.
type Unique struct {
	Name string
	// Columns are in declaration order.
	Columns []string
	// Constraint reports a UNIQUE constraint rather than a bare unique index.
	Constraint bool
	// Where is a partial unique index's predicate. A constraint cannot have
	// one, and a partial index never proves global uniqueness.
	Where Expr
	// NullsNotDistinct is PostgreSQL 15's UNIQUE NULLS NOT DISTINCT.
	NullsNotDistinct bool
}

// Total reports whether the object proves its columns are globally unique,
// which is what a to-one relation and a foreign key target need.
func (u Unique) Total() bool { return u.Where.Empty() && len(u.Columns) > 0 }

// Action is a foreign key's referential action.
type Action string

// The referential actions PostgreSQL supports. NoAction is the default and is
// rendered only when a caller asked for it explicitly.
const (
	NoAction   Action = "NO ACTION"
	Restrict   Action = "RESTRICT"
	Cascade    Action = "CASCADE"
	SetNull    Action = "SET NULL"
	SetDefault Action = "SET DEFAULT"
)

// ForeignKey is a foreign key constraint.
//
// Columns and RefColumns are pairwise aligned and in constraint order. The
// ordering is meaning, never a set.
type ForeignKey struct {
	Name       string
	Columns    []string
	RefSchema  string
	RefTable   string
	RefColumns []string
	OnDelete   Action
	OnUpdate   Action
	// Deferrable and InitiallyDeferred are PostgreSQL's constraint timing.
	Deferrable        bool
	InitiallyDeferred bool
	// NotValid reports a constraint added without checking existing rows, which
	// is how a foreign key is added to a large table without holding a lock
	// over every row in it.
	NotValid bool
}

// Check is a CHECK constraint.
type Check struct {
	Name       string
	Expression Expr
	// NotValid reports a constraint added without checking existing rows,
	// validated later with VALIDATE CONSTRAINT.
	NotValid bool
}

// Direction is an index column's sort order.
type Direction uint8

const (
	// Asc is PostgreSQL's default and renders nothing.
	Asc Direction = iota
	Desc
)

// Nulls is where an index column sorts NULLs.
type Nulls uint8

const (
	// NullsDefault is last for ascending and first for descending, which is
	// PostgreSQL's own rule and renders nothing.
	NullsDefault Nulls = iota
	NullsFirst
	NullsLast
)

// IndexColumn is one key column of an index.
type IndexColumn struct {
	// Name is the column, empty when the key is an expression.
	Name string
	// Expression is an expression key, such as lower(email). It is raw SQL and
	// deliberately so: pretending an expression index is a typed column would
	// be a lie about what can be checked.
	Expression Expr
	Direction  Direction
	Nulls      Nulls
	// OpClass is a non-default operator class, such as text_pattern_ops.
	OpClass string
}

// Index is an index as a schema object in its own right.
//
// Every index that is not owned by a constraint is described here, unique or
// not. A unique one is not additionally recorded as a [Unique]: it is one
// object, in one place.
type Index struct {
	Name string
	// Columns are the key columns, in order. Reordering them produces a
	// different index that answers different queries, so they are never sorted.
	Columns []IndexColumn
	// Include are covering columns, which are stored in the index but are not
	// part of the key and never prove uniqueness.
	Include []string
	Unique  bool
	// Method is btree, hash, gin, gist, brin or spgist. Empty means btree.
	Method string
	// Where is a partial index's predicate, and is part of the index's
	// identity: an index over the same columns with a different predicate is a
	// different index.
	Where Expr
	// Concurrently asks for CREATE INDEX CONCURRENTLY, which cannot run inside
	// a transaction and so decides how the whole migration executes.
	Concurrently bool
}

// TotalUnique reports whether the index proves global uniqueness.
func (i Index) TotalUnique() bool {
	if !i.Unique || !i.Where.Empty() || len(i.Columns) == 0 {
		return false
	}
	for _, c := range i.Columns {
		if c.Name == "" {
			return false
		}
	}
	return true
}

// ColumnNames returns the index's key columns, with an empty string where the
// key is an expression.
func (i Index) ColumnNames() []string {
	out := make([]string, 0, len(i.Columns))
	for _, c := range i.Columns {
		out = append(out, c.Name)
	}
	return out
}

// Table returns the named table and whether it exists.
func (s *Schema) Table(schemaName, name string) (Table, bool) {
	for _, t := range s.Tables {
		if t.Schema == schemaName && t.Name == name {
			return t, true
		}
	}
	return Table{}, false
}

// Enum returns the named enum and whether it exists.
func (s *Schema) Enum(schemaName, name string) (Enum, bool) {
	for _, e := range s.Enums {
		if e.Schema == schemaName && e.Name == name {
			return e, true
		}
	}
	return Enum{}, false
}

// Clone returns a deep copy.
//
// A migration state is mutated operation by operation, and a diff compares two
// states; sharing a slice between them would let applying one operation change
// what another comparison sees.
func (s *Schema) Clone() *Schema {
	if s == nil {
		return &Schema{}
	}
	out := &Schema{
		Extensions: slices.Clone(s.Extensions),
		Enums:      make([]Enum, 0, len(s.Enums)),
		Tables:     make([]Table, 0, len(s.Tables)),
	}
	for _, e := range s.Enums {
		e.Labels = slices.Clone(e.Labels)
		out.Enums = append(out.Enums, e)
	}
	for _, t := range s.Tables {
		out.Tables = append(out.Tables, t.Clone())
	}
	// Views travel with the schema they belong to. A clone that dropped them
	// would hand the migration planner a schema with no views in it, and every
	// check downstream — including the one that refuses to plan them — would
	// see nothing to refuse.
	for _, v := range s.Views {
		out.Views = append(out.Views, v.Clone())
	}
	for _, m := range s.MaterializedViews {
		out.MaterializedViews = append(out.MaterializedViews, m.Clone())
	}
	return out
}

// Clone returns a deep copy of one table.
func (t Table) Clone() Table {
	out := t
	out.Columns = slices.Clone(t.Columns)
	out.Uniques = make([]Unique, 0, len(t.Uniques))
	for _, u := range t.Uniques {
		u.Columns = slices.Clone(u.Columns)
		out.Uniques = append(out.Uniques, u)
	}
	out.ForeignKeys = make([]ForeignKey, 0, len(t.ForeignKeys))
	for _, f := range t.ForeignKeys {
		f.Columns = slices.Clone(f.Columns)
		f.RefColumns = slices.Clone(f.RefColumns)
		out.ForeignKeys = append(out.ForeignKeys, f)
	}
	out.Checks = slices.Clone(t.Checks)
	out.Indexes = make([]Index, 0, len(t.Indexes))
	for _, i := range t.Indexes {
		i.Columns = slices.Clone(i.Columns)
		i.Include = slices.Clone(i.Include)
		out.Indexes = append(out.Indexes, i)
	}
	if t.PrimaryKey != nil {
		pk := *t.PrimaryKey
		pk.Columns = slices.Clone(pk.Columns)
		out.PrimaryKey = &pk
	}
	return out
}

// Normalize puts a schema into its canonical order.
//
// Everything whose order carries no meaning is sorted, and everything whose
// order does — a table's columns, an index's keys, a constraint's columns — is
// left exactly as it is. Two schemas describing the same database therefore
// compare equal regardless of the order they were assembled in, which is what
// keeps a diff from reporting a change nobody made.
func (s *Schema) Normalize() {
	slices.SortFunc(s.Extensions, func(a, b Extension) int {
		return cmp.Or(cmp.Compare(a.Schema, b.Schema), cmp.Compare(a.Name, b.Name))
	})
	slices.SortFunc(s.Enums, func(a, b Enum) int { return cmp.Compare(a.Qualified(), b.Qualified()) })
	slices.SortFunc(s.Tables, func(a, b Table) int { return cmp.Compare(a.Qualified(), b.Qualified()) })
	for i := range s.Tables {
		s.Tables[i].normalize()
	}
	SortViews(s.Views)
	SortMaterializedViews(s.MaterializedViews)
	for i := range s.Views {
		SortRefs(s.Views[i].DependsOn)
	}
	for i := range s.MaterializedViews {
		SortRefs(s.MaterializedViews[i].DependsOn)
		slices.SortFunc(s.MaterializedViews[i].Indexes, func(a, b Index) int {
			return cmp.Compare(a.Name, b.Name)
		})
	}
}

// Normalize puts one table's constraints and indexes into canonical order,
// which is what an operation that added one calls so the state does not depend
// on the order operations happened to run in.
func (t *Table) Normalize() { t.normalize() }

func (t *Table) normalize() {
	slices.SortFunc(t.Uniques, func(a, b Unique) int { return cmp.Compare(a.Name, b.Name) })
	slices.SortFunc(t.ForeignKeys, func(a, b ForeignKey) int { return cmp.Compare(a.Name, b.Name) })
	slices.SortFunc(t.Checks, func(a, b Check) int { return cmp.Compare(a.Name, b.Name) })
	slices.SortFunc(t.Indexes, func(a, b Index) int { return cmp.Compare(a.Name, b.Name) })
}
