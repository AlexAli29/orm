package schema

import (
	"fmt"
	"io"
	"strings"
)

// Describing a schema for a person.
//
// This is not DDL. DDL is what the migration engine renders to run; this is
// what a reader is shown in a plan, a migration summary and an inspection, and
// the two have different jobs: one has to be accepted by PostgreSQL, the other
// has to be understood at a glance.
//
// It lives here rather than in the tools that print it so that a column looks
// the same wherever it appears. A summary and an inspection that formatted a
// default differently would make one schema look like two.

// FormatColumn renders a column the way a DDL reader expects to see it.
func FormatColumn(c Column) string {
	var b strings.Builder
	b.WriteString(c.Name)
	b.WriteString(" ")
	b.WriteString(c.Type.String())
	if c.Collation != "" {
		b.WriteString(" COLLATE " + c.Collation)
	}
	if !c.Nullable {
		b.WriteString(" NOT NULL")
	}
	if !c.Default.Empty() {
		b.WriteString(" DEFAULT " + string(c.Default))
	}
	switch c.Identity {
	case IdentityAlways:
		b.WriteString(" GENERATED ALWAYS AS IDENTITY")
	case IdentityByDefault:
		b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
	}
	if !c.Generated.Empty() {
		b.WriteString(" GENERATED ALWAYS AS (" + string(c.Generated) + ") STORED")
	}
	return b.String()
}

// FormatPrimaryKey renders a primary key.
func FormatPrimaryKey(k PrimaryKey) string {
	return fmt.Sprintf("primary key %s (%s)", k.Name, strings.Join(k.Columns, ", "))
}

// FormatUnique renders a unique constraint or index, over one or more lines.
//
// The two are not the same object and are never collapsed: only a constraint
// can be a foreign key's target, and only an index can be partial.
func FormatUnique(u Unique) []string {
	kind := "unique index"
	if u.Constraint {
		kind = "unique constraint"
	}
	lines := []string{fmt.Sprintf("%s %s (%s)", kind, u.Name, strings.Join(u.Columns, ", "))}
	if !u.Where.Empty() {
		lines = append(lines, "WHERE "+string(u.Where))
	}
	if u.NullsNotDistinct {
		lines = append(lines, "NULLS NOT DISTINCT")
	}
	return lines
}

// FormatForeignKey renders a foreign key constraint.
func FormatForeignKey(f ForeignKey) []string {
	line := fmt.Sprintf("foreign key %s (%s) -> %s (%s)", f.Name, strings.Join(f.Columns, ", "),
		ShortName(f.RefSchema, f.RefTable), strings.Join(f.RefColumns, ", "))
	if f.OnDelete != "" && f.OnDelete != NoAction {
		line += " ON DELETE " + string(f.OnDelete)
	}
	if f.OnUpdate != "" && f.OnUpdate != NoAction {
		line += " ON UPDATE " + string(f.OnUpdate)
	}
	if f.Deferrable {
		line += " DEFERRABLE"
		if f.InitiallyDeferred {
			line += " INITIALLY DEFERRED"
		}
	}
	if f.NotValid {
		line += " NOT VALID"
	}
	return []string{line}
}

// FormatCheck renders a check constraint.
func FormatCheck(c Check) []string {
	line := fmt.Sprintf("check %s (%s)", c.Name, c.Expression)
	if c.NotValid {
		line += " NOT VALID"
	}
	return []string{line}
}

// FormatIndex renders an index over one or more lines, keeping the key list,
// the predicate and the covering columns on lines of their own — those are the
// three things a reader checks, and running them together hides all three.
func FormatIndex(i Index) []string {
	head := "index " + i.Name
	if i.Unique {
		head = "unique index " + i.Name
	}
	if i.Concurrently {
		head += " CONCURRENTLY"
	}
	if m := i.Method; m != "" && m != "btree" {
		head += " USING " + m
	}
	keys := make([]string, 0, len(i.Columns))
	for _, c := range i.Columns {
		key := c.Name
		if c.Name == "" {
			key = "(" + string(c.Expression) + ")"
		}
		if c.OpClass != "" {
			key += " " + c.OpClass
		}
		if c.Direction == Desc {
			key += " DESC"
		}
		switch c.Nulls {
		case NullsFirst:
			key += " NULLS FIRST"
		case NullsLast:
			key += " NULLS LAST"
		}
		keys = append(keys, key)
	}
	lines := []string{head, "(" + strings.Join(keys, ", ") + ")"}
	if !i.Where.Empty() {
		lines = append(lines, "WHERE "+string(i.Where))
	}
	if len(i.Include) > 0 {
		lines = append(lines, "INCLUDE ("+strings.Join(i.Include, ", ")+")")
	}
	return lines
}

// FormatTable renders everything declared on a table, without its header.
//
// An object that needs more than one line — an index with a predicate, a
// partial unique — has its continuation lines indented under its own first
// line, so a listing of a whole table stays readable as a tree rather than
// running together into one column.
func FormatTable(t Table) []string {
	var lines []string
	nest := func(item []string) {
		for i, line := range item {
			if i == 0 {
				lines = append(lines, line)
				continue
			}
			lines = append(lines, "    "+line)
		}
	}
	for _, c := range t.Columns {
		lines = append(lines, FormatColumn(c))
	}
	if t.PrimaryKey != nil {
		lines = append(lines, FormatPrimaryKey(*t.PrimaryKey))
	}
	for _, u := range t.Uniques {
		nest(FormatUnique(u))
	}
	for _, f := range t.ForeignKeys {
		nest(FormatForeignKey(f))
	}
	for _, c := range t.Checks {
		nest(FormatCheck(c))
	}
	for _, i := range t.Indexes {
		nest(FormatIndex(i))
	}
	return lines
}

// ShortName drops the schema qualifier for public, which is where almost
// everything lives and where repeating it adds noise rather than information.
func ShortName(schemaName, name string) string {
	if schemaName == "" || schemaName == "public" {
		return name
	}
	return schemaName + "." + name
}

// Text writes a whole schema for a person to read.
//
// The schema is normalised first, so two runs against one database produce the
// same text and the output can be committed and diffed like anything else.
func Text(w io.Writer, s *Schema) error {
	out := s.Clone()
	out.Normalize()

	var b strings.Builder
	if len(out.Extensions) > 0 {
		b.WriteString("extensions\n")
		for _, e := range out.Extensions {
			name := e.Name
			if e.Schema != "" {
				name += " schema " + e.Schema
			}
			b.WriteString("    " + name + "\n")
		}
		b.WriteString("\n")
	}
	for _, e := range out.Enums {
		fmt.Fprintf(&b, "enum %s\n    %s\n\n", e.Qualified(), strings.Join(e.Labels, ", "))
	}
	for _, t := range out.Tables {
		fmt.Fprintf(&b, "table %s\n", t.Qualified())
		for _, line := range FormatTable(t) {
			b.WriteString("    " + line + "\n")
		}
		b.WriteString("\n")
	}
	if b.Len() == 0 {
		b.WriteString("the schema is empty\n")
	}
	_, err := io.WriteString(w, b.String())
	return err
}
