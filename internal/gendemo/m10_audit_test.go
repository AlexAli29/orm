// A raw typed expression is a trust boundary: the caller states the result
// type and this package believes them. What is required is that a wrong
// statement fails cleanly.
func TestAudit_rawValueIsATrustBoundary(t *testing.T) {
	testdb.AdminDSN(t)
	db := db(t)

	// Declared non-null, returns NULL: a scan error, not a zero value.
	lying := orm.Project1(
		orm.RawValue[gendemo.User, string]("NULL::text"),
		func(s string) string { return s },
	)
	_, err := orm.Select(db.Users, lying).All(t.Context())
	if err == nil {
		t.Error("a NULL scanned into a non-nullable destination without complaint")
	}

	// Declared nullable, returns NULL: the honest form works.
	honest := orm.Project1(
		orm.RawValue[gendemo.User, *string]("NULL::text"),
		func(s *string) *string { return s },
	)
	got, err := orm.Select(db.Users, honest).Limit(1).All(t.Context())
	if err != nil {
		t.Fatalf("All: %v", err)
	}
	if len(got) != 1 || got[0] != nil {
		t.Errorf("got %v, want one NULL", got)
	}

	// Declared as the wrong type: a scan error rather than a wrong value.
	wrong := orm.Project1(
		orm.RawValue[gendemo.User, int64]("'not a number'::text"),
		func(n int64) int64 { return n },
	)
	if _, err := orm.Select(db.Users, wrong).All(t.Context()); err == nil {
		t.Error("text scanned into int64 without complaint")
	}

	// Its own placeholders are renumbered into the statement.
	args := orm.Project2(
		orm.RawValue[gendemo.User, string]("upper($1)", "shout"),
		gendemo.Users.Email,
		func(a, b string) string { return a },
	)
	sql, params, err := orm.Select(db.Users, args).Where(gendemo.Users.ID.Eq(1)).SQL()
	if err != nil {
		t.Fatalf("SQL: %v", err)
	}
	if !strings.Contains(sql, "upper($1)") || fmt.Sprint(params) != "[shout 1]" {
		t.Errorf("SQL = %s, args = %v", sql, params)
	}
	out, err := orm.Select(db.Users, args).Where(gendemo.Users.ID.Eq(1)).One(t.Context())
	if err != nil {
		t.Fatalf("One: %v", err)
	}
	if out != "SHOUT" {
		t.Errorf("got %q", out)
	}
}

