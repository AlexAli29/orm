// A projection streams; nothing materialises an entity on the way.
func TestAudit_projectionStreamsLarge(t *testing.T) {
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, schema(t)+`
		INSERT INTO users (id, email, age, tags, settings)
		  SELECT g, 'u'||g||'@example.com', 30, '{}', '{}' FROM generate_series(1, 50000) g;`)
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatalf("parsing the DSN: %v", err)
	}
	cfg.MaxConns = 2
	cfg.AfterConnect = gendemo.RegisterTypes
	pool, err := pgxpool.NewWithConfig(t.Context(), cfg)
	if err != nil {
		t.Fatalf("opening a pool: %v", err)
	}
	defer pool.Close()
	db := gendemo.New(pool)

	shape := orm.Project1(gendemo.Users.ID, func(id int64) int64 { return id })
	n := 0
	for _, err := range orm.Select(db.Users, shape).Rows(t.Context()) {
		if err != nil {
			t.Fatalf("Rows: %v", err)
		}
		n++
	}
	if n != 50000 {
		t.Fatalf("streamed %d rows", n)
	}
	// Break in the middle, then cancel in the middle, then acquire both
	// connections to prove neither was left out.
	seen := 0
	for _, err := range orm.Select(db.Users, shape).Rows(t.Context()) {
		if err != nil {
			t.Fatalf("Rows: %v", err)
		}
		seen++
		if seen == 25000 {
			break
		}
	}
	ctx, cancel := context.WithCancel(t.Context())
	seen = 0
	for _, err := range orm.Select(db.Users, shape).Rows(ctx) {
		if err != nil {
			break
		}
		seen++
		if seen == 100 {
			cancel()
		}
	}
	cancel()

	acquire, stop := context.WithTimeout(t.Context(), 10*time.Second)
	defer stop()
	conns := make([]*pgxpool.Conn, 0, 2)
	for range 2 {
		c, err := pool.Acquire(acquire)
		if err != nil {
			t.Fatalf("the pool never recovered: %v", err)
		}
		conns = append(conns, c)
	}
	for _, c := range conns {
		c.Release()
	}
	if used := pool.Stat().AcquiredConns(); used != 0 {
		t.Errorf("%d connections are still checked out", used)
	}
}
