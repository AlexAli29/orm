// The M10 audit.
//
// These are the tests that try to break the projection, aggregate and write
// expression layers rather than to demonstrate them. The three things they are
// looking for, in order: a NULL that became a Go zero value, a type this
// package claims that PostgreSQL does not agree with, and a mutation that
// touched rows the caller did not describe.

// ------------------------------------------------ PostgreSQL is the authority

// Every result type M10 states statically is checked against pg_typeof.
//
// A table of promotions written from memory is a table of beliefs. This asks
// the server what each expression actually returns, so a wrong entry fails here
// rather than as a scan error in somebody's application.
func TestAudit_expressionTypesMatchPostgres(t *testing.T) {
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, `
		CREATE TABLE nums (
		    id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		    a2  smallint NOT NULL,
		    a4  integer NOT NULL,
		    a8  bigint NOT NULL,
		    f4  real NOT NULL,
		    f8  double precision NOT NULL,
		    n   numeric NOT NULL,
		    ts  timestamptz NOT NULL,
		    txt text NOT NULL
		);
		INSERT INTO nums (a2, a4, a8, f4, f8, n, ts, txt) VALUES
		  (1, 1, 1, 1.5, 1.5, 1.5, '2024-01-01T00:00:00Z', 'a'),
		  (2, 2, 2, 2.5, 2.5, 2.5, '2024-02-01T00:00:00Z', 'b');`)
	conn, err := pgx.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.WithoutCancel(t.Context())) })

	typeOf := func(sqlExpr string) string {
		t.Helper()
		var name string
		if err := conn.QueryRow(t.Context(),
			"SELECT pg_typeof("+sqlExpr+")::text FROM nums LIMIT 1").Scan(&name); err != nil {
			t.Fatalf("pg_typeof(%s): %v", sqlExpr, err)
		}
		return name
	}
	grouped := func(sqlExpr string) string {
		t.Helper()
		var name string
		if err := conn.QueryRow(t.Context(),
			"SELECT pg_typeof("+sqlExpr+")::text FROM nums").Scan(&name); err != nil {
			t.Fatalf("pg_typeof(%s): %v", sqlExpr, err)
		}
		return name
	}

	// What this package claims, expression by expression. The Go type is the
	// one the constructor's signature produces; the SQL type is what the
	// server must agree it is.
	for _, tt := range []struct {
		what   string
		sql    string
		wantPG string
		// aggregate marks the ones that need no GROUP BY and collapse the rows.
		aggregate bool
	}{
		{"sum(smallint)", "sum(a2)", "bigint", true},
		{"sum(integer)", "sum(a4)", "bigint", true},
		{"sum(bigint)", "sum(a8)", "numeric", true},
		{"sum(real)", "sum(f4)", "real", true},
		{"sum(double precision)", "sum(f8)", "double precision", true},
		{"sum(numeric)", "sum(n)", "numeric", true},
		{"avg(smallint)", "avg(a2)", "numeric", true},
		{"avg(integer)", "avg(a4)", "numeric", true},
		{"avg(bigint)", "avg(a8)", "numeric", true},
		{"avg(real)", "avg(f4)", "double precision", true},
		{"avg(double precision)", "avg(f8)", "double precision", true},
		{"avg(numeric)", "avg(n)", "numeric", true},
		{"count(*)", "count(*)", "bigint", true},
		{"count(expr)", "count(a4)", "bigint", true},
		{"min(integer)", "min(a4)", "integer", true},
		{"max(integer)", "max(a4)", "integer", true},
		{"min(timestamptz)", "min(ts)", "timestamp with time zone", true},
		{"max(text)", "max(txt)", "text", true},
		// The arithmetic this package builds, which is always between two
		// values of one type.
		{"smallint + smallint", "a2 + a2", "smallint", false},
		{"integer + integer", "a4 + a4", "integer", false},
		{"bigint + bigint", "a8 + a8", "bigint", false},
		{"real + real", "f4 + f4", "real", false},
		{"double + double", "f8 + f8", "double precision", false},
		{"numeric + numeric", "n + n", "numeric", false},
		{"integer / integer", "a4 / a4", "integer", false},
		{"smallint * smallint", "a2 * a2", "smallint", false},
	} {
		got := typeOf(tt.sql)
		if tt.aggregate {
			got = grouped(tt.sql)
		}
		if got != tt.wantPG {
			t.Errorf("%s: PostgreSQL returns %s, this package is written for %s",
				tt.what, got, tt.wantPG)
		}
	}
}

// ----------------------------------------------------------- NULL, everywhere

// nullDB has one row of values and one row of NULLs, where every value is the
// Go zero of its type. That is the shape that catches a NULL collapsing: if
// nullability were lost, the two rows would be indistinguishable.
func nullDB(t *testing.T) (*gendemo.DB, *pgx.Conn) {
	t.Helper()
	dsn := testdb.Create(t, schema(t)+`
		INSERT INTO users (id, email, age, active, state, nickname, score, tags, settings,
		                   avatar, manager_id, bio, visits, deleted_at, created_at) VALUES
		  (1, 'zero@example.com',  0, false, 'pending', '',   0,    '{}', '{}', '\x'::bytea, NULL, '',   0,    '2024-01-01T00:00:00Z', '2024-01-01T00:00:00Z'),
		  (2, 'nulls@example.com', 0, false, 'pending', NULL, NULL, '{}', '{}', NULL,        NULL, NULL, NULL, NULL,                   '2024-01-01T00:00:00Z');
		SELECT setval(pg_get_serial_sequence('users','id'), 1000);`)
	conn, err := pgx.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.WithoutCancel(t.Context())) })
	return gendemo.New(conn), conn
}

// A NULL never arrives as a zero value, for any nullable category the fixture
// maps — and the row beside it holds exactly that zero value, so a collapse
// would make the two rows equal.
func TestAudit_nullNeverBecomesZero(t *testing.T) {
	testdb.AdminDSN(t)
	db, conn := nullDB(t)

	type row struct {
		ID       int64
		Nickname *string
		Score    *float64
		Avatar   *[]byte
		Visits   *int64
		Deleted  *time.Time
	}
	shape := orm.Project6(
		gendemo.Users.ID, gendemo.Users.Nickname, gendemo.Users.Score,
		gendemo.Users.Avatar, gendemo.Users.Visits, gendemo.Users.DeletedAt,
		func(id int64, nick *string, score *float64, avatar *[]byte, visits *int64, del *time.Time) row {
			return row{id, nick, score, avatar, visits, del}
		},
	)
	got, err := orm.Select(db.Users, shape).OrderBy(gendemo.Users.ID.Asc()).All(t.Context())
	if err != nil {
		t.Fatalf("All: %v", err)
	}
	if len(got) != 2 {
		t.Fatalf("got %d rows", len(got))
	}

	// Row 1 holds the zero values, and every one of them is present.
	zero := got[0]
	if zero.Nickname == nil || *zero.Nickname != "" {
		t.Errorf("an empty string came back as %v", zero.Nickname)
	}
	if zero.Score == nil || *zero.Score != 0 {
		t.Errorf("a zero float came back as %v", zero.Score)
	}
	if zero.Avatar == nil || len(*zero.Avatar) != 0 {
		t.Errorf("an empty bytea came back as %v", zero.Avatar)
	}
	if zero.Visits == nil || *zero.Visits != 0 {
		t.Errorf("a zero bigint came back as %v", zero.Visits)
	}
	if zero.Deleted == nil {
		t.Error("a stored timestamp came back as NULL")
	}

	// Row 2 holds NULLs, and every one of them is absent.
	nulls := got[1]
	for name, present := range map[string]bool{
		"nickname": nulls.Nickname != nil, "score": nulls.Score != nil,
		"avatar": nulls.Avatar != nil, "visits": nulls.Visits != nil,
		"deleted_at": nulls.Deleted != nil,
	} {
		if present {
			t.Errorf("%s was NULL and came back present", name)
		}
	}

	// PostgreSQL agrees, asked directly.
	var pgNick *string
	if err := conn.QueryRow(t.Context(), "SELECT nickname FROM users WHERE id = 2").Scan(&pgNick); err != nil {
		t.Fatalf("handwritten: %v", err)
	}
	if pgNick != nil {
		t.Errorf("the fixture is wrong: nickname is not NULL")
	}
}

// Arithmetic propagates NULL, so an expression over a nullable column is
// nullable. This is the runtime half of the compile-time rule.
func TestAudit_arithmeticPropagatesNull(t *testing.T) {
	testdb.AdminDSN(t)
	db, conn := nullDB(t)

	shape := orm.Project1(
		gendemo.Users.Visits.Add(1),
		func(v *int64) *int64 { return v },
	)
	got, err := orm.Select(db.Users, shape).OrderBy(gendemo.Users.ID.Asc()).All(t.Context())
	if err != nil {
		t.Fatalf("All: %v", err)
	}
	if got[0] == nil || *got[0] != 1 {
		t.Errorf("0 + 1 = %v, want 1", got[0])
	}
	if got[1] != nil {
		t.Errorf("NULL + 1 = %v, want NULL", *got[1])
	}

	var want *int64
	if err := conn.QueryRow(t.Context(), "SELECT visits + 1 FROM users WHERE id = 2").Scan(&want); err != nil {
		t.Fatalf("handwritten: %v", err)
	}
	if want != nil {
		t.Fatal("the fixture is wrong: NULL + 1 is not NULL")
	}
}

// ------------------------------------------------------- positional binding

// The contract is positional, so two expressions of one Go type must not be
// silently interchangeable. This is the test that would fail if the select list
// and the scanner ever drifted apart.
func TestAudit_projectionIsPositional(t *testing.T) {
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, `
		CREATE TABLE pairs (a text NOT NULL, b text NOT NULL, m bigint NOT NULL, n bigint NOT NULL);
		INSERT INTO pairs VALUES ('first', 'second', 10, 20);`)
	conn, err := pgx.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.WithoutCancel(t.Context())) })

	src := orm.NewSource("public", "pairs")
	type pairs struct{}
	meta := orm.EntityMeta[pairs]{
		Table:   orm.TableID{Schema: "public", Name: "pairs"},
		Source:  src,
		Columns: []orm.ColumnMeta{{Name: "a", Field: "A"}},
		Dest:    func(*pairs, int) any { return new(string) },
	}
	repo := orm.NewRepo(conn, &meta)
	a := orm.NewTextCol[pairs](src, "a")
	b := orm.NewTextCol[pairs](src, "b")
	m := orm.NewOrdCol[pairs, int64](src, "m")
	n := orm.NewOrdCol[pairs, int64](src, "n")

	type out struct {
		A, B string
		M, N int64
	}
	got, err := orm.Select(repo, orm.Project4(a, b, m, n,
		func(a, b string, m, n int64) out { return out{a, b, m, n} })).One(t.Context())
	if err != nil {
		t.Fatalf("One: %v", err)
	}
	if got.A != "first" || got.B != "second" || got.M != 10 || got.N != 20 {
		t.Fatalf("positions were not preserved: %+v", got)
	}

	// Swapping the expressions swaps the values, which proves the binding is
	// positional rather than by name or by luck.
	swapped, err := orm.Select(repo, orm.Project4(b, a, n, m,
		func(a, b string, m, n int64) out { return out{a, b, m, n} })).One(t.Context())
	if err != nil {
		t.Fatalf("One: %v", err)
	}
	if swapped.A != "second" || swapped.B != "first" || swapped.M != 20 || swapped.N != 10 {
		t.Fatalf("swapping the expressions did not swap the values: %+v", swapped)
	}
}

// A result alias names a column of the result and nothing else. Awkward ones
// have to survive quoting.
func TestAudit_aliasQuoting(t *testing.T) {
	testdb.AdminDSN(t)
	db := db(t)

	for _, alias := range []string{
		"select", "GROUP", "a b", `a"b`, "Ünïcödé", strings.Repeat("x", 63),
		"MixedCase", "mixedcase",
	} {
		shape := orm.Project1(gendemo.Users.Email.As(alias), func(s string) string { return s })
		sql, _, err := orm.Select(db.Users, shape).SQL()
		if err != nil {
			t.Errorf("alias %q: SQL: %v", alias, err)
			continue
		}
		if !strings.Contains(sql, `"`+strings.ReplaceAll(alias, `"`, `""`)+`"`) {
			t.Errorf("alias %q was not quoted: %s", alias, sql)
		}
		if _, err := orm.Select(db.Users, shape).All(t.Context()); err != nil {
			t.Errorf("alias %q: All: %v", alias, err)
		}
	}

	// Two results cannot claim one name.
	dup := orm.Project2(
		gendemo.Users.ID.As("x"), gendemo.Users.Email.As("x"),
		func(id int64, s string) string { return s },
	)
	if _, _, err := orm.Select(db.Users, dup).SQL(); err == nil {
		t.Error("two results named x were accepted")
	} else if !strings.Contains(err.Error(), "identifies one column") {
		t.Errorf("err = %v", err)
	}

	// Aliases differing only in case are two names, as PostgreSQL quotes them.
	mixed := orm.Project2(
		gendemo.Users.ID.As("X"), gendemo.Users.Email.As("x"),
		func(id int64, s string) string { return s },
	)
	if _, _, err := orm.Select(db.Users, mixed).SQL(); err != nil {
		t.Errorf("quoted aliases differing in case were refused: %v", err)
	}
}

// ------------------------------------------------------- expression immutability

// Every expression this package hands out is a value. Reusing one must not
// change what another query compiles to, and nothing may reach back into a
// generated descriptor.
func TestAudit_expressionsAreImmutable(t *testing.T) {
	testdb.AdminDSN(t)
	db := db(t)

	// One aggregate, three different filters. Each must see only its own.
	base := orm.Count[gendemo.User]()
	active := base.Filter(gendemo.Users.Active.Eq(true))
	banned := base.Filter(gendemo.Users.State.Eq(gendemo.UserStateBanned))
	distinct := base.Distinct()

	shape := orm.Project4(base, active, banned, distinct,
		func(all, a, b, d int64) [4]int64 { return [4]int64{all, a, b, d} })
	sql, _, err := orm.Select(db.Users, shape).SQL()
	if err != nil {
		t.Fatalf("SQL: %v", err)
	}
	if strings.Count(sql, "FILTER") != 2 {
		t.Errorf("filters leaked between aggregates: %s", sql)
	}
	if !strings.HasPrefix(sql, "SELECT count(*), count(*) FILTER") {
		t.Errorf("the unfiltered aggregate inherited a filter: %s", sql)
	}

	got, err := orm.Select(db.Users, shape).One(t.Context())
	if err != nil {
		t.Fatalf("One: %v", err)
	}
	if got[0] != 3 || got[1] != 2 || got[2] != 1 {
		t.Errorf("counts = %v, want [3 2 1 ...]", got)
	}

	// The same value expression in two clauses, and in two queries.
	shared := gendemo.Users.Age.Add(1)
	one := orm.Select(db.Users, orm.Project1(shared, func(v int32) int32 { return v }))
	two := orm.Select(db.Users, orm.Project1(shared, func(v int32) int32 { return v })).
		Where(gendemo.Users.ID.Gt(1))
	sqlOne, _, err := one.SQL()
	if err != nil {
		t.Fatalf("SQL: %v", err)
	}
	if _, _, err := two.SQL(); err != nil {
		t.Fatalf("SQL: %v", err)
	}
	sqlAgain, _, err := one.SQL()
	if err != nil {
		t.Fatalf("SQL: %v", err)
	}
	if sqlOne != sqlAgain {
		t.Errorf("building a second query changed the first:\n  %s\n  %s", sqlOne, sqlAgain)
	}

	// An assignment expression reused across two updates.
	inc := gendemo.Users.Age.Add(1)
	a, _, err := db.Users.Update().Set(gendemo.Users.Age.SetExpr(inc)).Where(gendemo.Users.ID.Eq(1)).SQL()
	if err != nil {
		t.Fatalf("SQL: %v", err)
	}
	b, _, err := db.Users.Update().Set(gendemo.Users.Age.SetExpr(inc)).Where(gendemo.Users.ID.Eq(2)).SQL()
	if err != nil {
		t.Fatalf("SQL: %v", err)
	}
	if strings.Replace(a, "= $2", "", 1) != strings.Replace(b, "= $2", "", 1) {
		t.Errorf("a reused assignment differs between builders:\n  %s\n  %s", a, b)
	}
}

// The same expressions, built from many goroutines at once.
func TestAudit_expressionsAreRaceFree(t *testing.T) {
	testdb.AdminDSN(t)
	db := db(t)

	shape := orm.Project2(gendemo.Users.ID, gendemo.Users.Email,
		func(id int64, email string) UserSummary { return UserSummary{id, email} })

	var wg sync.WaitGroup
	for range 32 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			_ = orm.Count[gendemo.User]().Filter(gendemo.Users.Active.Eq(true)).Distinct().As("n")
			_ = gendemo.Users.Age.Add(1)
			_ = gendemo.Users.Email.As("addr")
			_ = orm.Excluded(gendemo.Users.Nickname)
			q := orm.Select(db.Users, shape).
				Where(gendemo.Users.Active.Eq(true)).
				GroupBy(gendemo.Users.ID, gendemo.Users.Email).
				Having(orm.Count[gendemo.User]().Gt(0)).
				Distinct()
			if _, _, err := q.Clone().SQL(); err != nil {
				t.Errorf("SQL: %v", err)
			}
			_, _, _ = orm.UpdateReturning(
				db.Users.Update().Set(gendemo.Users.Age.SetExpr(gendemo.Users.Age.Add(1))).
					Where(gendemo.Users.ID.Eq(1)), shape).SQL()
		}()
	}
	wg.Wait()

	sql, _, err := orm.Select(db.Users, shape).SQL()
	if err != nil {
		t.Fatalf("SQL: %v", err)
	}
	if strings.Contains(sql, "addr") || strings.Contains(sql, "DISTINCT") ||
		strings.Contains(sql, "GROUP BY") {
		t.Errorf("a per-query option reached the shared shape: %s", sql)
	}
}

// ------------------------------------------------------------ the mutations

// A write is exactly the write the builder described. One reports afterwards
// and never narrows it, and there is no statement before or after.
func TestAudit_writeAffectsTheDescribedRowset(t *testing.T) {
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, schema(t)+`
		INSERT INTO users (id, email, age, tags, settings)
		  SELECT g, 'u'||g||'@example.com', 10, '{}', '{}' FROM generate_series(1, 5) g;
		SELECT setval(pg_get_serial_sequence('users','id'), 1000);`)
	conn, err := pgx.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.WithoutCancel(t.Context())) })
	ex := &countingExecutor{Executor: conn}
	db := gendemo.New(ex)

	ex.reset()
	_, err = orm.UpdateReturning(
		db.Users.Update().Set(gendemo.Users.Age.SetExpr(gendemo.Users.Age.Add(1))).All(),
		userSummaries,
	).One(t.Context())
	if !errors.Is(err, orm.ErrMultipleRows) {
		t.Fatalf("One = %v, want ErrMultipleRows", err)
	}
	// One statement, and all five rows changed.
	if ex.n != 1 {
		t.Errorf("the write ran %d statements, want 1", ex.n)
	}
	var changed int
	if err := conn.QueryRow(t.Context(), "SELECT count(*) FROM users WHERE age = 11").Scan(&changed); err != nil {
		t.Fatalf("counting: %v", err)
	}
	if changed != 5 {
		t.Errorf("%d rows changed; One must not narrow the mutation", changed)
	}
	// And the statement carries no LIMIT.
	sql, _, err := orm.UpdateReturning(
		db.Users.Update().Set(gendemo.Users.Age.Set(1)).All(), userSummaries).SQL()
	if err != nil {
		t.Fatalf("SQL: %v", err)
	}
	if strings.Contains(strings.ToUpper(sql), "LIMIT") {
		t.Errorf("the write carries a LIMIT: %s", sql)
	}

	// A delete returns the rows as they were, in one statement, with nothing
	// selected before or after.
	ex.reset()
	gone, err := orm.DeleteReturning(
		db.Users.Delete().Where(gendemo.Users.ID.Lte(2)), userSummaries).All(t.Context())
	if err != nil {
		t.Fatalf("All: %v", err)
	}
	if len(gone) != 2 {
		t.Fatalf("deleted %v", gone)
	}
	if ex.n != 1 {
		t.Errorf("the delete ran %d statements, want 1", ex.n)
	}
	var left int
	if err := conn.QueryRow(t.Context(), "SELECT count(*) FROM users").Scan(&left); err != nil {
		t.Fatalf("counting: %v", err)
	}
	if left != 3 {
		t.Errorf("%d rows remain, want 3", left)
	}
}

// An expression assignment is computed by PostgreSQL, not by Go. Two concurrent
// increments therefore both land.
func TestAudit_noReadModifyWrite(t *testing.T) {
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, schema(t)+`
		INSERT INTO users (id, email, age, tags, settings)
		  VALUES (1, 'c@example.com', 0, '{}', '{}');`)
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatalf("parsing the DSN: %v", err)
	}
	cfg.AfterConnect = gendemo.RegisterTypes
	pool, err := pgxpool.NewWithConfig(t.Context(), cfg)
	if err != nil {
		t.Fatalf("opening a pool: %v", err)
	}
	defer pool.Close()
	db := gendemo.New(pool)

	const n = 50
	var wg sync.WaitGroup
	for range n {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if _, err := db.Users.Update().
				Set(gendemo.Users.Age.SetExpr(gendemo.Users.Age.Add(1))).
				Where(gendemo.Users.ID.Eq(1)).Exec(t.Context()); err != nil {
				t.Errorf("Exec: %v", err)
			}
		}()
	}
	wg.Wait()

	conn, err := pgx.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	defer func() { _ = conn.Close(context.WithoutCancel(t.Context())) }()
	var age int32
	if err := conn.QueryRow(t.Context(), "SELECT age FROM users WHERE id = 1").Scan(&age); err != nil {
		t.Fatalf("reading back: %v", err)
	}
	// A read-modify-write in Go would lose updates; PostgreSQL's own
	// arithmetic under row locks does not.
	if age != n {
		t.Errorf("age = %d after %d concurrent increments; increments were lost", age, n)
	}
}

// A conflict WHERE restricts the update, not the insert.
func TestAudit_conflictWhereLocality(t *testing.T) {
	testdb.AdminDSN(t)
	db := emptyDB(t)

	first := newUser("c@example.com")
	first.Age = 10
	if _, err := db.Users.Insert(t.Context(), first); err != nil {
		t.Fatalf("Insert: %v", err)
	}

	// The condition holds, so the update runs.
	again := newUser("c@example.com")
	again.Age = 99
	got, err := db.Users.Insert(t.Context(), again,
		orm.OnConflict(gendemo.Users.Email).
			Where(gendemo.Users.Age.Lt(50)).
			DoUpdateSet(gendemo.Users.Age.SetExpr(gendemo.Users.Age.Add(1))),
	)
	if err != nil {
		t.Fatalf("Insert: %v", err)
	}
	if got.Age != 11 {
		t.Errorf("age = %d, want 11", got.Age)
	}

	// Now it does not, so PostgreSQL updates nothing and returns no row. The
	// insert still ran and still conflicted — the condition governs the update.
	if _, err := db.Users.Insert(t.Context(), again,
		orm.OnConflict(gendemo.Users.Email).
			Where(gendemo.Users.Age.Gt(1000)).
			DoUpdateSet(gendemo.Users.Age.SetExpr(gendemo.Users.Age.Add(1))),
	); !errors.Is(err, orm.ErrConflictIgnored) {
		t.Errorf("Insert = %v, want ErrConflictIgnored", err)
	}
	// And exactly one row exists: the conflict was not turned into an insert.
	n, err := db.Users.Query().Count(t.Context())
	if err != nil {
		t.Fatalf("Count: %v", err)
	}
	if n != 1 {
		t.Errorf("%d rows, want 1", n)
	}

	sql, _, err := db.Users.InsertSQL([]gendemo.User{again},
		orm.OnConflict(gendemo.Users.Email).
			Where(gendemo.Users.Age.Lt(50)).
			DoUpdateSet(gendemo.Users.Age.SetExpr(gendemo.Users.Age.Add(1))),
	)
	if err != nil {
		t.Fatalf("InsertSQL: %v", err)
	}
	// The WHERE belongs to the DO UPDATE, and there is no other one.
	if !strings.Contains(sql, `DO UPDATE SET "age" = "users"."age" + $`) ||
		!strings.Contains(sql, `WHERE "users"."age" < $`) {
		t.Errorf("SQL = %s", sql)
	}
	if strings.Count(strings.ToUpper(sql), " WHERE ") != 1 {
		t.Errorf("the conflict condition leaked into another clause: %s", sql)
	}
}

