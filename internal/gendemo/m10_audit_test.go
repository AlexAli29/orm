// A numeric result is never a float. The aggregate constructors that produce
// numeric take the Go type as a parameter, so the only thing to check is that
// nothing quietly widens or narrows on the way.
func TestAudit_numericIsNeverAFloat(t *testing.T) {
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, `
		CREATE TABLE money (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount numeric(20,4) NOT NULL);
		INSERT INTO money (amount) VALUES (0.1), (0.2), (12345678901234.5678);`)
	conn, err := pgx.Connect(t.Context(), dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close(context.WithoutCancel(t.Context())) })

	src := orm.NewSource("public", "money")
	type money struct{}
	meta := orm.EntityMeta[money]{
		Table:   orm.TableID{Schema: "public", Name: "money"},
		Source:  src,
		Columns: []orm.ColumnMeta{{Name: "id", Field: "ID"}},
		Dest:    func(*money, int) any { return new(int64) },
	}
	repo := orm.NewRepo(conn, &meta)
	amount := orm.NewOrdCol[money, pgtype.Numeric](src, "amount")

	shape := orm.Project1(
		orm.SumNumeric[money, pgtype.Numeric](amount),
		func(v *pgtype.Numeric) *pgtype.Numeric { return v },
	)
	got, err := orm.Select(repo, shape).One(t.Context())
	if err != nil {
		t.Fatalf("One: %v", err)
	}
	if got == nil || !got.Valid {
		t.Fatalf("sum = %v", got)
	}
	var want pgtype.Numeric
	if err := conn.QueryRow(t.Context(), "SELECT sum(amount) FROM money").Scan(&want); err != nil {
		t.Fatalf("handwritten: %v", err)
	}
	a, _ := got.Value()
	b, _ := want.Value()
	if fmt.Sprint(a) != fmt.Sprint(b) {
		t.Errorf("sum = %v, PostgreSQL says %v", a, b)
	}
	// The exact digits survived: a float64 would have lost them.
	if !strings.Contains(fmt.Sprint(a), "12345678901234") {
		t.Errorf("precision was lost: %v", a)
	}
}

