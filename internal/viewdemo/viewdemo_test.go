// Refresh replaces the contents, and the view sees the new rows.
func TestMatView_refresh(t *testing.T) {
	db, pool := open(t)
	if _, err := pool.Exec(t.Context(),
		`INSERT INTO orders (user_id, price) VALUES (3, '99.00')`); err != nil {
		t.Fatalf("inserting: %v", err)
	}

	before, err := db.UserTotals.Query().Where(viewdemo.UserTotals.UserID.Eq(3)).All(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	if len(before) != 1 || before[0].Orders != 0 {
		t.Fatalf("the materialized view already sees the new order: %+v", before)
	}

	if err := db.UserTotals.Refresh(t.Context()); err != nil {
		t.Fatalf("refreshing: %v", err)
	}
	after, err := db.UserTotals.Query().Where(viewdemo.UserTotals.UserID.Eq(3)).All(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	if len(after) != 1 || after[0].Orders != 1 {
		t.Errorf("after a refresh the view reports %+v", after)
	}
}

