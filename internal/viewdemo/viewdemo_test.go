// M16.5 Stage A: views and materialized views as query sources.
//
// Everything here goes through the ordinary Query builder. There is no view
// query path to test, which is the point — a view is a source, and the compiler
// below it never learns otherwise.

const schemaSQL = `
CREATE TABLE users (
	id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email      text NOT NULL,
	active     boolean NOT NULL,
	created_at timestamptz NOT NULL DEFAULT now(),
	settings   jsonb NOT NULL DEFAULT '{}',
	last_ip    inet
);
CREATE TABLE orders (
	id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id bigint NOT NULL REFERENCES users(id),
	price   numeric NOT NULL
);

CREATE VIEW active_users AS
	SELECT id, email, created_at, settings FROM users WHERE active;

CREATE VIEW user_orders AS
	SELECT u.id AS user_id, u.email, o.price
	FROM users u LEFT JOIN orders o ON o.user_id = u.id;

CREATE MATERIALIZED VIEW user_totals AS
	SELECT u.id AS user_id, count(o.id) AS orders, sum(o.price) AS total
	FROM users u LEFT JOIN orders o ON o.user_id = u.id
	GROUP BY u.id WITH DATA;
CREATE UNIQUE INDEX user_totals_user_id_key ON user_totals (user_id);

INSERT INTO users (email, active) VALUES
	('a@example.com', true), ('b@example.com', true), ('quiet@example.com', true);
INSERT INTO users (email, active) VALUES ('gone@example.com', false);
INSERT INTO orders (user_id, price) VALUES (1, '10.00'), (1, '5.00'), (2, '7.50');
REFRESH MATERIALIZED VIEW user_totals;
`

func open(t *testing.T) (*viewdemo.DB, *pgxpool.Pool) {
	t.Helper()
	testdb.AdminDSN(t)
	dsn := testdb.Create(t, schemaSQL)
	pool, err := pgxpool.New(t.Context(), dsn)
	if err != nil {
		t.Fatalf("opening: %v", err)
	}
	t.Cleanup(pool.Close)
	return viewdemo.New(pool), pool
}

// A view reads through the ordinary builder.
func TestView_reads(t *testing.T) {
	db, _ := open(t)
	rows, err := db.ActiveUsers.Query().
		Where(viewdemo.ActiveUsers.Email.Like("%@example.com")).
		OrderBy(viewdemo.ActiveUsers.Email.Asc()).
		Limit(2).
		All(t.Context())
	if err != nil {
		t.Fatalf("reading the view: %v", err)
	}
	if len(rows) != 2 {
		t.Fatalf("got %d rows, want 2", len(rows))
	}
	if rows[0].Email != "a@example.com" {
		t.Errorf("first row is %s", rows[0].Email)
	}
	// The inactive user is not in the view, which is the view's own predicate
	// doing its job rather than anything the ORM added.
	all, err := db.ActiveUsers.Query().All(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	if len(all) != 3 {
		t.Errorf("the view returned %d rows, want 3", len(all))
	}
}

// Release-critical: a view column that the definition can leave NULL scans as
// NULL, even though its base column is NOT NULL.
func TestView_outerJoinNullabilitySurvives(t *testing.T) {
	db, _ := open(t)
	rows, err := db.UserOrders.Query().
		Where(viewdemo.UserOrders.Email.Eq("quiet@example.com")).
		All(t.Context())
	if err != nil {
		t.Fatalf("reading: %v", err)
	}
	if len(rows) != 1 {
		t.Fatalf("got %d rows, want 1", len(rows))
	}
	if rows[0].Price != nil {
		t.Errorf("price = %q, want NULL: orders.price is NOT NULL on its table and "+
			"the view's LEFT JOIN still produces NULL for a user with no orders", *rows[0].Price)
	}
}

// A view joins a table, and the join goes through the ordinary composition
// layer. Nothing here is view-aware: a view is a *Source, and From/Join take a
// *Source, so this is the same code path a table join takes.
func TestView_joinsATable(t *testing.T) {
	_, pool := open(t)
	id := orm.Named("id", orm.Of(viewdemo.ActiveUsers.ID))
	sql, _, err := orm.Rows(id).
		From(viewdemo.ActiveSource()).
		LeftJoin(viewdemo.UsersSource(), orm.Cond(viewdemo.Users.Active.Eq(true))).
		Using(pool).
		SQL()
	if err != nil {
		t.Fatalf("building: %v", err)
	}
	if !strings.Contains(sql, "active_users") || !strings.Contains(sql, `"users"`) {
		t.Errorf("the join names neither relation:\n%s", sql)
	}
}

// Three aliases of one view stay three sources. A view's identity is its
// pointer exactly as a table's is, so this is the frozen source-identity system
// rather than anything new.
func TestView_selfJoinKeepsSourceIdentity(t *testing.T) {
	_, pool := open(t)
	a := viewdemo.ActiveSource().As("a")
	b := viewdemo.ActiveSource().As("b")
	c := viewdemo.ActiveSource().As("c")
	col := func(src *orm.Source) orm.OrdCol[viewdemo.ActiveUser, int64] {
		return orm.NewOrdCol[viewdemo.ActiveUser, int64](src, "id")
	}

	sql, _, err := orm.Rows(orm.Named("id", orm.Of(col(a)))).
		From(a).
		Join(b, orm.Cond(col(b).EqCol(col(a)))).
		Join(c, orm.Cond(col(c).EqCol(col(b)))).
		Using(pool).
		SQL()
	if err != nil {
		t.Fatalf("building: %v", err)
	}
	for _, alias := range []string{`"a"`, `"b"`, `"c"`} {
		if !strings.Contains(sql, alias) {
			t.Errorf("the alias %s collapsed:\n%s", alias, sql)
		}
	}
}

// A view in a CTE, joined to a materialized view: both are sources and the
// compiler below never learns which kind of relation either is.
func TestView_composesWithCTEsAndMatViews(t *testing.T) {
	_, pool := open(t)
	vid := orm.Named("id", orm.Of(viewdemo.ActiveUsers.ID))
	cte := orm.CTE("recent", orm.Rows(vid).From(viewdemo.ActiveSource()))

	sql, _, err := orm.Rows(orm.Named("id", orm.Ref(cte, vid))).
		With(cte).
		From(cte).
		LeftJoin(viewdemo.TotalsSource(), orm.Cond(viewdemo.UserTotals.Orders.Gte(0))).
		Using(pool).
		SQL()
	if err != nil {
		t.Fatalf("building: %v", err)
	}
	for _, want := range []string{"WITH", "recent", "active_users", "user_totals", "LEFT JOIN"} {
		if !strings.Contains(sql, want) {
			t.Errorf("the statement does not contain %q:\n%s", want, sql)
		}
	}
}

